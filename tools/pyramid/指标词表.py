def _num(x: float) -> str:
    """边界数字文本化：整数去 .0（15.0→'15'）；其余按 %g（0.7→'0.7'、0.05→'0.05'）。"""
    if x == int(x):
        return str(int(x))
    return f"{x:g}"


def _pct(x: float) -> str:
    """0~1 比例边界 → 百分数文本（0.2→'20'、0.05→'5'）。配 单位='%' 用。"""
    return _num(x * 100)


def render_区间(档位表: Sequence[tuple], fmt: Callable[[float], str] = _num,
              单位: str = "") -> str:
    """从档位表 [(上界,档名,解释),...] 渲染紧凑区间串（单一真源·防漂移）。

    规则：**末档=顶档**，渲染 '档名>上一档上界'（兼容 inf / 1e9 / 1.01 等有限哨兵，
    不依赖顶档上界值）；其余档渲染 '档名≤上界'。单位（如 '%'）附在每个边界后。
    档位表为空 → 返回 ''。
    """
    if not 档位表:
        return ""
    parts = []
    prev: Optional[float] = None
    n = len(档位表)
    for i, (上界, 档名, _解) in enumerate(档位表):
        if i == n - 1:  # 顶档：> 上一档上界（不读顶档哨兵值）
            parts.append(f"{档名}>{fmt(prev)}{单位}" if prev is not None else str(档名))
        else:
            parts.append(f"{档名}≤{fmt(上界)}{单位}")
        prev = 上界
    return " / ".join(parts)


