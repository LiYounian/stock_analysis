"""Prompt 模板集中管理(可版本化)。

每个 LLM 触点一个模板,schema 与 docs/计划/P2C_新闻情绪LLM.md §2 一一对应。
写法:描述性约束(只抄原文、禁编造、拿不准留空/中性),强制 JSON,给全字段 schema。
"""

# —— L1:新闻关键信息提取 ——
# schema 精简自 9 字段 → 6 字段:删掉下游未消费的 涉及主体/关键数字/时间
# (grep tools+web 确认无引用;新闻条目的展示时间走原始 news 的 time 字段,非 LLM 抽取的「时间」),
# 以减少输出 token / 加速。保留字段均有明确下游消费:
#   事件类型→classify_events 三层归类;影响方向/影响强度/与本股关系→aggregate_sentiment 打分 + news_ai + web;
#   摘要→news_ai 评论;原因→news_ai 原因 + 详情页。
NEWS_EXTRACT_SCHEMA = {
    "事件类型": "业绩/政策/合作/诉讼/产品/人事/市场传闻/其他 之一",
    "影响方向": "利好/利空/中性 之一(对目标股票而言)",
    "影响强度": "1~5 整数(1弱5强)",
    "与本股关系": "直接/间接/无关 之一(新闻是否真的关于目标股票,防蹭词)",
    "摘要": "一句话中文摘要",
    "原因": "一句话说明判定该影响方向/强度的依据(只据原文,禁编造;拿不准留空)",
}


def news_extract_instruction(name: str, code: str) -> str:
    """L1 抽取指令。只抄原文事实、禁推断编造;拿不准的字段留空/中性。"""
    return (
        f"你是金融信息抽取助手。下面是一条与股票【{name}({code})】可能相关的新闻,"
        f"请抽取结构化信息。要求:\n"
        f"- 只依据原文,禁止编造或外部推断;拿不准的字段留空或填'中性'。\n"
        f"- '影响方向'是这条新闻对【{name}】股价的方向(利好/利空/中性)。\n"
        f"- '与本股关系':若新闻只是顺带提及代码/名称、主体并非{name},填'无关';"
        f"直接讲{name}自身填'直接';讲行业/同板块间接影响填'间接'。\n"
        f"- '影响强度'按对{name}的实质影响给 1~5。\n"
        f"- '原因'用一句话说明你判定该影响方向/强度的依据(只据原文,禁编造;拿不准留空)。\n"
        f"只输出一个 JSON,不要任何解释/多余文字。")


# —— 政策打分:判某条政策对相关行业的方向/强度 ——
POLICY_SCORE_SCHEMA = {
    "影响方向": "利好/利空/中性 之一(对相关行业整体而言)",
    "影响强度": "1~5 整数(1弱5强)",
    "受影响行业": "list[str],该政策实质影响到的行业/板块;无则空列表",
}


def policy_score_instruction(sectors: list[str] | None = None) -> str:
    """政策打分指令。判该政策对相关行业的方向/强度;只依据原文,拿不准填中性。"""
    hint = ""
    if sectors:
        hint = (f"\n- 候选行业(命中票池板块,供参考,不必局限于此):"
                f"{'、'.join(sectors)}。")
    return (
        "你是宏观/行业政策研判助手。下面是一条政策/宏观新闻,请判断它对相关行业的影响。"
        "要求:\n"
        "- 只依据原文事实,禁止编造或外部推断;拿不准时'影响方向'填'中性'、'影响强度'填 1。\n"
        "- '影响方向'是该政策对受影响行业整体基本面的方向(利好/利空/中性)。\n"
        "- '影响强度'按政策力度/覆盖面给 1~5。\n"
        "- '受影响行业'列出该政策实质影响的行业/板块名。"
        f"{hint}")


# —— UGC 舆情:判一批股吧帖的整体情绪 ——
UGC_SENTIMENT_SCHEMA = {
    "净情绪": "-1~1 的小数(-1极空,0中性,+1极多),整批帖子的整体情绪倾向",
    "多空": "偏多/偏空/中性 之一",
    "依据": "一句话中文说明判断依据(高频观点/情绪)",
}


def ugc_sentiment_instruction(name: str, code: str) -> str:
    """UGC 整体情绪判定指令。对一批股吧帖判整体多空,禁被个别极端帖带偏。"""
    return (
        f"你是股吧舆情分析助手。下面是关于股票【{name}({code})】的一批股吧帖子(每行一条),"
        f"请判断这批帖子对该股的**整体**情绪。要求:\n"
        f"- 综合全部帖子给整体倾向,不要被个别极端/灌水/广告帖带偏。\n"
        f"- '净情绪'是 -1~1 的小数:整体看空取负、看多取正、分歧或中性取 0 附近。\n"
        f"- 拿不准或噪声过大时,'净情绪'填 0、'多空'填'中性'。\n"
        f"- 只依据帖子内容,不做外部推断。")


# —— 事件类型 → 情绪三层(代码映射,不再调 LLM)——
TYPE_TO_LAYER = {
    "政策": "政策", "业绩": "公司行为", "合作": "公司行为", "诉讼": "公司行为",
    "产品": "公司行为", "人事": "公司行为", "市场传闻": "舆情", "其他": "舆情",
}


def type_to_layer(event_type: str) -> str:
    return TYPE_TO_LAYER.get(event_type, "舆情")
