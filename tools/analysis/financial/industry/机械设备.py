"""机械设备(申万一级,含工程机械/通用设备/专用设备/机器人/自动化)财报专家(P0 数值层)。
⚠️ 非投资建议;阈值/区间/权重均为工程占位,待策略提供者标定。

行业画像:重资产制造,**强周期(工程机械看回款/周期)与成长(机器人/减速器/自动化看订单/研发)双属性**。
  - 在建工程/扩产:资本开支扩产能,在建工程/资产总计偏高 → 军备竞赛式扩产,需求转弱时变负担/减值。
  - 订单/合同负债:合同负债(预收)是设备订单景气指标,环比下滑 → 订单转弱、需求见顶。
  - 应收账款回款风险(工程机械命门):工程机械分期收款/融资租赁、账期长,应收/营收偏高或应收增速远超营收
    增速 → 回款质量恶化(下行周期坏账高发),是本行业最需盯的风险。
  - 存货积压:需求转弱时产成品/在制品积压,存货增速远超营收增速 → 跌价减值。
  - 研发迭代(机器人/自动化):新兴高端制造技术迭代快,研发投入不足 → 被路线替代掉队;传统工程机械研发
    占比天然低,故研发不足仅作**低严重度提示**(表内难分新兴/传统,见 NOTE)。
  - 毛利率与周期:机械毛利随周期波动(周期上行毛利修复、下行价格战),故 SKIP 通用「毛利率异常跳升」
    (周期修复的毛利跳升是常态非操纵),改用低毛利/回款/订单视角。
  - 重资产高杠杆偏常态(设备制造),**不 skip 高负债**,交由通用区间承接。

阈值/区间/权重均为工程占位,注释注明"待标定"。纯函数、无状态、缺值→不命中/None,不抛异常。
"""
