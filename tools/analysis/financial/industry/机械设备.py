# 本行业不适用/会误杀的通用红旗:
#   毛利率异常跳升 —— 机械毛利随周期波动,周期上行的毛利修复跳升是**常态**非操纵,通用版会误杀,SKIP。
# 高负债:重资产设备制造高杠杆偏常态,**不 skip**,由通用区间承接。
SKIP_FLAGS = ["毛利率异常跳升"]


def _ratio(a, b):
    """a/b;a、b 任一 None 或 |b|≈0 → None。"""
    if a is None or b is None or abs(b) < 1e-9:
        return None
    return a / b


# ── 专属红旗阈值 ──────────────────────────────────────────────────────
# 标定 2026-08(feat/industry-threshold-calib):机械设备 11 票 / 132 报告期(2023Q3~2026Q2,
#   时序严格锚披露日),分布锚定(见 _calibration.py)。机械行业应收账期结构性偏长,原占位过松易泛滥。
_HI_应收占营收 = 1.0         # [标定 0.4→1.0] 应收/营收>此→回款慢/账期长。原0.4≈行业中位(命中62%=泛滥,机械应收
                            #   结构性高);1.0≈p75,逮真·回款异常尾部(分布 p50≈0.9/p85=1.69/p90=2.18)
_应收超营收增速_GAP = 20.0    # 应收增速领先营收>此pct→回款恶化。分布 p80≈17/p85=27,命中≈21%,保留
_HI_在建占总资产 = 0.10      # [标定 0.15→0.10] 在建/总资产>此→扩产激进。原0.15>p90=0.098(命中2.5%=近乎从不发声);
                            #   0.10≈p90,逮激进扩产尾部(分布 p75=0.052/p85=0.083)
_LO_合同负债环比 = -15.0     # 合同负债环比<此→订单转弱。分布 p10≈-33,命中≈23%,保留(合同负债波动大,不再收紧)
_存货超营收增速_GAP = 25.0    # 存货增速领先营收>此pct→产成品积压。分布 p85≈27,命中≈16%(尾部),保留
_LO_研发费用率 = 2.0         # 研发费用率<此→研发不足。分布 p10≈1.8,命中≈14%(下尾),低severity,保留


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """机械设备专属红旗。返回 [{code,命中,严重度,值}, ...](调用方仅并入 命中=True 的)。
    单期、纯函数,一切缺值→不命中,不抛异常。阈值为工程占位,**待标定**。"""
    derived = derived or {}
    利润表 = (structured or {}).get("利润表", {}) if isinstance(structured, dict) else {}
    资产负债表 = (structured or {}).get("资产负债表", {}) if isinstance(structured, dict) else {}
    现金流量表 = (structured or {}).get("现金流量表", {}) if isinstance(structured, dict) else {}

    flags: list[dict] = []

    def add(code, sev, val):
        flags.append({"code": code, "命中": True, "严重度": sev, "值": val})

    营收增速 = derived.get("营收增速")

    # ① 应收回款风险(工程机械命门)—— 高
    # 判据:应收账款/营收 偏高,或 应收增速 远超营收增速。工程机械分期/融资租赁账期长,下行周期坏账高发。
    应收 = (资产负债表.get("应收账款")
          or 资产负债表.get("应收票据及应收账款"))
    营收 = 利润表.get("营业总收入") or 利润表.get("营业收入")
    r_ar = _ratio(应收, 营收)
    应收增速 = derived.get("应收增速")
    hit_ar = False
    val_ar: dict = {"NOTE": "工程机械账期长/分期回款,下行周期坏账高发"}
    if r_ar is not None and r_ar > _HI_应收占营收:
        hit_ar = True
        val_ar.update({"应收账款": 应收, "营业收入": 营收, "应收占营收": round(r_ar, 4)})
    elif (应收增速 is not None and 营收增速 is not None
            and 应收增速 > 0 and (应收增速 - 营收增速) > _应收超营收增速_GAP):
        hit_ar = True
        val_ar.update({"应收增速": 应收增速, "营收增速": 营收增速,
                       "差值pct": round(应收增速 - 营收增速, 4)})
    if hit_ar:
        add("应收回款风险", "高", val_ar)

    # ② 扩产激进(在建工程占比高)—— 中
    # 判据:在建工程 / 资产总计 偏高 → 军备竞赛式扩产,需求转弱/产能过剩时变负担、面临在建减值。
    在建工程 = 资产负债表.get("在建工程")
    资产总计 = 资产负债表.get("资产总计")
    r_capex = _ratio(在建工程, 资产总计)
    if r_capex is not None and r_capex > _HI_在建占总资产:
        add("扩产激进", "中",
            {"在建工程": 在建工程, "资产总计": 资产总计, "在建占总资产": round(r_capex, 4),
             "NOTE": "扩产能,需求转弱时变负担/减值"})

    # ③ 订单转弱(合同负债/预收环比下滑)—— 中
    # 判据:合同负债(订单/预收)环比 显著负增 → 在手订单转弱、需求见顶(机器人/自动化尤为领先)。
    合同负债环比 = derived.get("合同负债环比")
    if 合同负债环比 is not None and 合同负债环比 < _LO_合同负债环比:
        add("订单转弱", "中",
            {"合同负债环比": round(合同负债环比, 4), "下限pct": _LO_合同负债环比,
             "NOTE": "合同负债(预收)是设备订单景气指标,环比骤降=订单/需求转弱"})

    # ④ 存货积压(需求转弱跌价减值)—— 中
    # 判据:存货增速 领先 营收增速 超阈值且在增 → 产成品/在制品积压,需求转弱面临跌价减值。
    存货增速 = derived.get("存货增速")
    if (存货增速 is not None and 营收增速 is not None
            and 存货增速 > 0 and (存货增速 - 营收增速) > _存货超营收增速_GAP):
        add("存货积压", "中",
            {"存货增速": 存货增速, "营收增速": 营收增速, "差值pct": round(存货增速 - 营收增速, 4),
             "NOTE": "需求转弱产成品积压,面临跌价减值"})

    # ⑤ 经营现金流恶化(回款反噬)—— 中
    # 判据:归母为正而经营活动现金流量净额为负(账面赚钱但没收到现金,回款差)。
    归母 = 利润表.get("归母净利润")
    CFO = 现金流量表.get("经营活动现金流量净额")
    if isinstance(归母, (int, float)) and isinstance(CFO, (int, float)) and 归母 > 0 > CFO:
        add("经营现金流恶化", "中", {"归母净利润": 归母, "经营活动现金流量净额": CFO,
                                "NOTE": "账面赚钱但回款差(工程机械回款反噬)"})

    # ⑥ 研发投入不足(新兴高端制造迭代掉队)—— 低
    # 说明:机器人/减速器/自动化技术迭代快,研发费用率过低 → 有被路线替代风险;但传统工程机械研发占比天然低,
    #      表内难分新兴/传统,故仅**低严重度**发声,不当强信号(真实业务结构待正文补采)。
    研发费用率 = derived.get("研发费用率")
    if 研发费用率 is not None and 研发费用率 < _LO_研发费用率:
        add("研发投入不足", "低",
            {"研发费用率": round(研发费用率, 4), "下限pct": _LO_研发费用率,
             "NOTE": "新兴高端制造迭代快,研发不足有掉队风险;传统工程机械研发占比天然低,仅提示"})

    return flags
