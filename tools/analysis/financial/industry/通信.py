# ————————————————— 专属红旗阈值(工程占位,待标定)—————————————————
# 标定 2026-08(feat/industry-threshold-calib):当前财报快照池内**无通信行业票(0 覆盖)**,无从做分布
#   标定,下列阈值**全部保留工程占位**、不硬编;待池内出现通信票后由 _calibration.py 标定。
_GM_DROP_PCT = -3.0        # 毛利率同比降幅达此(百分点)判"毛利率下滑"(高:结构恶化/价格战)
_INV_GAP_PCT = 30.0        # 存货增速−营收增速超此(pct)且毛利率同步走弱 → 存货畸高滞销
_AR_GAP_PCT = 20.0         # 应收增速−营收增速超此(pct)→ 应收暴增于营收
_CONTRACT_DROP_PCT = -10.0  # 合同负债环比低于此(pct)→ 订单/景气转弱
_REV_HI_PCT = 20.0         # 判"高增长"的营收增速下限(供研发/利润背离红旗做前置条件)
_RD_MIN_PCT = 3.0          # 高增期研发费用率低于此(%)→ 研发投入偏弱(下一代掉队风险)
_PROFIT_LAG_PCT = 40.0     # 营收增速−扣非增速超此(pct)且营收高增 → 增收利润背离(价格战/费用失控)


def _num(rec: dict | None, *path: str):
    """安全取嵌套数值科目;任一层缺/非数 → None。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """通信(光模块/设备)专属红旗。返回成形 {code,命中,严重度,值};仅 命中=True 者会并入结果。
    一切缺值 → 该条不命中;纯函数不抛异常。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code: str, sev: str, val: dict):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    营收增速 = derived.get("营收增速")
    扣非增速 = derived.get("扣非净利增速")
    毛利率同比升 = derived.get("毛利率同比升")   # analyzer 注入(同比绝对百分点变动),可能缺
    存货增速 = derived.get("存货增速")
    应收增速差 = derived.get("应收营收增速差")
    合同负债环比 = derived.get("合同负债环比")
    研发费用率 = derived.get("研发费用率")

    # 1) 毛利率下滑(高):产品结构恶化 / 价格战。用同比降幅代理"连续下滑"(季报无多期历史,注实现状态)。
    if 毛利率同比升 is not None and 毛利率同比升 <= _GM_DROP_PCT:
        emit("毛利率下滑", "高", {"毛利率同比升pct": round(毛利率同比升, 4), "阈值pct": _GM_DROP_PCT})

    # 2) 存货畸高滞销(中):存货增速远超营收增速,且毛利率同步走弱(区分良性备货 vs 滞销)。
    #    仅在能确认毛利率走弱时命中,避免对旺季前备货误杀。
    if (存货增速 is not None and 营收增速 is not None and 毛利率同比升 is not None
            and (存货增速 - 营收增速) > _INV_GAP_PCT and 毛利率同比升 < 0):
        emit("存货畸高滞销", "中", {"存货增速": 存货增速, "营收增速": 营收增速,
                               "差值pct": round(存货增速 - 营收增速, 4),
                               "毛利率同比升pct": round(毛利率同比升, 4)})

    # 3) 应收暴增于营收(中):靠赊销冲收入。优先用现成派生"应收营收增速差",缺则退回原子相减。
    _ar_gap = 应收增速差
    if _ar_gap is None:
        _ar, _rev = derived.get("应收增速"), 营收增速
        _ar_gap = (_ar - _rev) if (_ar is not None and _rev is not None) else None
    if _ar_gap is not None and _ar_gap > _AR_GAP_PCT:
        emit("应收暴增于营收", "中", {"应收营收增速差pct": round(_ar_gap, 4), "阈值pct": _AR_GAP_PCT})

    # 4) 合同负债转弱(中):预收/订单景气环比负增 → 需求见顶信号(光模块下游 capex 拐点前瞻)。
    if 合同负债环比 is not None and 合同负债环比 <= _CONTRACT_DROP_PCT:
        emit("合同负债转弱", "中", {"合同负债环比pct": round(合同负债环比, 4), "阈值pct": _CONTRACT_DROP_PCT})

    # 5) 研发投入偏弱(低):营收高增但研发费用率偏低 → 下一代(1.6T/CPO/硅光)后劲存疑。
    #    绝对额同比需相邻期研发费用(季报单期不可得),此处用"高增期研发费用率<下限"作代理(注实现状态)。
    if (营收增速 is not None and 营收增速 > _REV_HI_PCT
            and 研发费用率 is not None and 研发费用率 < _RD_MIN_PCT):
        emit("研发投入偏弱", "低", {"营收增速": 营收增速, "研发费用率": round(研发费用率, 4),
                               "下限pct": _RD_MIN_PCT})

    # 6) 增收利润背离(中):营收高增但扣非增速显著落后(价格战 / 费用失控)。
    #    补通用"增收不增利"(仅利润负增才命中)之不足:利润仍正增但远跑输营收也预警。
    if (营收增速 is not None and 扣非增速 is not None
            and 营收增速 > _REV_HI_PCT and (营收增速 - 扣非增速) > _PROFIT_LAG_PCT):
        emit("增收利润背离", "中", {"营收增速": 营收增速, "扣非净利增速": 扣非增速,
                               "增速差pct": round(营收增速 - 扣非增速, 4), "阈值pct": _PROFIT_LAG_PCT})

    return out
