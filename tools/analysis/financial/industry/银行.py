"""银行财报专家(P0 数值层)。⚠️ 非投资建议;阈值/区间/权重均为工程占位,待策略提供者标定。

设计依据:docs/财报分析专家/银行_财报分析方案.md。
核心思路:通用五维按制造业口径设计(毛利率/存货周转/短债覆盖/资产负债率上限),对银行**完全失效**,
会系统性压低城商行(成都银行 601838、宁波银行 002142)。本模块:
  1. 覆写五维子指标 → 用银行口径的 derived 键(营收增速_银行 / 成本收入比 / 非息收入占比 / 存贷比 / ROA 等);
  2. 覆写五维权重 → 资产质量(命门是坏账不是增长)给最高权重;
  3. SKIP_FLAGS 跳掉对银行不适用的通用红旗(毛利率跳升等,金融业已跳过的高负债类为并集冗余);
  4. extra_flags 用 structured 原始科目自算银行专属红旗(拨备/成本/存贷比/收入结构)。

数据可得性(见方案 §5):三大表 by_report 对银行给了专属科目(利息净收入/信用减值损失_金融/
业务及管理费/发放贷款/吸收存款 等),足以做"盈利结构+规模+拨备强度代理+效率";但
**不良率 / 拨备覆盖率 / 拨贷比 / 资本充足率 / 官方净息差** 属附注披露项,akshare 三大表拿不到,
本模块相关子指标/红旗用**代理指标**近似并在 NOTE 标注,真监管比率待补采后接入(方案 §5.3)。
"""
from __future__ import annotations

KEY = "银行"          # 申万一级规范名,必须正好为此字符串,否则 analyzer 路由不到
NOTE = ("银行按专属口径评分:营收取『营业收入』(通用营收增速对银行为空);"
        "重点看 成本收入比/非息收入占比/存贷比/拨备前利润/ROA/ROE;"
        "毛利率/存货周转/短债覆盖/资产负债率上限等通用指标对银行不适用已剔除。"
        "不良率/拨备覆盖率/资本充足率/官方净息差为附注披露项、akshare 暂未采集,"
        "相关维度与红旗用代理指标近似(减值/拨备前利润 等),真指标待补采。")


# ── 工程占位阈值(待标定)────────────────────────────────────────────────
# 五维区间:每项 (显示名, derived 键, 0分端, 100分端);反向指标 0分端>100分端。
# 键状态两类:
#   ✅ 可得 —— metrics.compute_derived 已产出(含 M4 新增 总资产增速/贷款增速/减值占PPOP/PPOP覆盖减值倍数);
#   ⏳ 待补采 —— 不良率/拨备覆盖率/核心一级资本充足率/资本充足率/拨贷比/净息差,属监管附注披露项,
#              akshare 三大表拿不到,需另接数据源;five_dims 对缺失子项自动取可得子项均值,故列出不影响
#              当前打分,补采后即可直接生效(方案 §4/§5.3)。
_SPECS = {
    # 成长(权重 15%):规模扩表 + 营收/净利增速
    "成长": [
        ("总资产(生息资产)增速%", "总资产增速", -5, 20),      # ✅ 可得(M4:资产总计同比)
        ("发放贷款增速%", "贷款增速", -5, 20),                 # ✅ 可得(M4:发放贷款同比)
        ("营业收入增速%", "营收增速_银行", -10, 20),           # ✅ 可得(用营业收入,非营业总收入)
        ("归母净利增速%", "归母净利增速", -10, 20),            # ✅ 可得
    ],
    # 质量 = 资产质量 + 盈利结构(权重 30%,最重):坏账是银行命门
    "质量": [
        ("拨备覆盖率%", "拨备覆盖率", 150, 400),               # ⏳ 待补采(监管下限 150%)
        ("不良率%(反向)", "不良率", 3.0, 0.5),                # ⏳ 待补采
        ("信用减值损失强度(反向,减值/PPOP)", "减值占PPOP", 0.8, 0.1),  # ✅ 可得(M4:代理)
        ("非息收入占比%", "非息收入占比", 5, 35),              # ✅ 可得
        ("扣非占归母", "扣非占归母", 0.7, 1.0),                # ✅ 可得(防非经常损益虚增)
    ],
    # 健康 = 资本充足 + 拨备缓冲(权重 15%):通用资产负债率/短债覆盖/商誉全剔除
    "健康": [
        ("核心一级资本充足率%", "核心一级资本充足率", 8.0, 13.0),  # ⏳ 待补采
        ("资本充足率(总)%", "资本充足率", 11.0, 16.0),          # ⏳ 待补采
        ("拨贷比%", "拨贷比", 2.5, 4.0),                        # ⏳ 待补采
        ("PPOP覆盖信用减值倍数(代理缓冲厚度)", "PPOP覆盖减值倍数", 1.0, 4.0),  # ✅ 可得(M4:代理缓冲厚度)
    ],
    # 运营(权重 15%):效率
    "运营": [
        ("成本收入比%(反向)", "成本收入比", 45, 25),          # ✅ 可得(业管费/营收,越低越好)
        ("ROA%", "ROA", 0.5, 1.2),                             # ✅ 可得
        ("存贷比%(反向上限,过高负债偏紧)", "存贷比", 100, 75),  # ✅ 可得
    ],
    # 回报(权重 25%):股东回报与主业息差
    "回报": [
        ("ROE%", "ROE", 8, 16),                                # ✅ 可得
        ("净息差 NIM%", "净息差", 1.4, 2.4),                   # 待补采/代理
    ],
}

# 五维权重(方案 §4.6):资产质量最高权,其次回报;成长/健康/运营各 15%。待标定。
_WEIGHTS = {"成长": 0.15, "质量": 0.30, "健康": 0.15, "运营": 0.15, "回报": 0.25}

# ── 专属红旗阈值(工程占位,待标定)──────────────────────────────────────
_成本收入比_上限_pct = 45.0    # 业管费/营收 高于此 → 运营效率差
_减值占PPOP_下限 = 0.05        # 信用减值/拨备前利润 低于此 → 计提偏低(利润质量存疑,代理)
_存贷比_上限_pct = 100.0       # 发放贷款/吸收存款 高于此 → 资金运用过满、负债端偏紧
_非息占比_下限_pct = 10.0      # 非息收入占比 低于此 → 过度依赖息差,抗息差下行弱

# 本行业不适用的通用红旗(§4 清单)。金融业 is_financial 已跳过
# 【高负债/现金含量不足/短债覆盖不足/应收存货激增】,此处再显式列入为并集冗余,
# 并补跳【毛利率异常跳升】(银行无营业成本→无毛利率,该红旗对银行无意义)。
SKIP_FLAGS = ["高负债", "现金含量不足", "短债覆盖不足", "应收存货激增", "毛利率异常跳升"]


def dimension_specs() -> dict:
    """覆写五维子指标区间(格式同 scoring.dimension_specs)。"""
    return {dim: [tuple(sub) for sub in subs] for dim, subs in _SPECS.items()}


def weights() -> dict | None:
    """覆写五维权重;资产质量给最高权。"""
    return dict(_WEIGHTS)


def _num(rec, *path):
    """安全取嵌套数值科目;任一层缺/非数 → None。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def _ratio(a, b):
    """a/b;a、b 任一 None 或 |b|≈0 → None。"""
    if a is None or b is None or abs(b) < 1e-9:
        return None
    return a / b


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """银行专属红旗(单期,纯函数,一切缺值→不命中,不抛)。

    仅实现 akshare 单期数据即可算的**代理红旗**(方案 §3 标 ✅ 中不依赖同比历史的那些):
    成本收入比走高 / 拨备计提力度不足 / 拨备前利润为负 / 存贷比过高 / 非息收入占比过低。
    依赖同比历史的红旗(减值同比大增、PPOP 负增长、成本收入比恶化、拨备反哺、存款落后贷款、
    NIM 收窄)与需补采监管比率的红旗(不良率上升、拨备覆盖率跌破线、资本充足率逼近线、
    关注类激增)在单期接口下不判(缺历史/缺数据不误杀),待衍生层/采集层补齐后接入。
    """
    derived = derived or {}
    flags: list[dict] = []

    # 1) 成本收入比走高:业务及管理费 / 营业收入(自算优先,回退 derived);反向,越低越好。
    业管费 = _num(structured, "利润表", "业务及管理费")
    营业收入 = _num(structured, "利润表", "营业收入")
    cir = _ratio(业管费, 营业收入)
    cir = round(cir * 100, 4) if cir is not None else derived.get("成本收入比")
    if cir is not None and cir > _成本收入比_上限_pct:
        flags.append({"code": "成本收入比走高", "命中": True, "严重度": "低",
                      "值": {"成本收入比%": round(cir, 2), "上限%": _成本收入比_上限_pct}})

    # 2) 拨备计提力度不足(代理):信用减值损失 / 拨备前营业利润(PPOP)过低,且 PPOP>0。
    #    NOTE:拨备覆盖率/不良率 akshare 未采,此处以"减值占 PPOP 偏低"代理"计提偏薄→利润质量存疑"。
    ppop = derived.get("拨备前营业利润")
    减值 = _num(structured, "利润表", "信用减值损失_金融")
    dr = _ratio(减值, ppop)
    if dr is not None and ppop is not None and ppop > 0 and dr < _减值占PPOP_下限:
        flags.append({"code": "拨备计提力度不足", "命中": True, "严重度": "中",
                      "值": {"减值占PPOP": round(dr, 4), "下限": _减值占PPOP_下限,
                            "NOTE": "代理指标(拨备覆盖率/不良率待补采)"}})

    # 3) 拨备前利润为负:剔除拨备后主业已亏(PPOP<0),盈利根基走坏。
    if ppop is not None and ppop < 0:
        flags.append({"code": "拨备前利润为负", "命中": True, "严重度": "中",
                      "值": {"拨备前营业利润": ppop}})

    # 4) 存贷比过高:发放贷款及垫款 / 吸收存款 过高 → 资金运用过满、负债端偏紧。
    ldr = _ratio(_num(structured, "资产负债表", "发放贷款及垫款"),
                 _num(structured, "资产负债表", "吸收存款"))
    ldr = round(ldr * 100, 4) if ldr is not None else derived.get("存贷比")
    if ldr is not None and ldr > _存贷比_上限_pct:
        flags.append({"code": "存贷比过高", "命中": True, "严重度": "低",
                      "值": {"存贷比%": round(ldr, 2), "上限%": _存贷比_上限_pct}})

    # 5) 非息收入占比过低:(营业收入 − 利息净收入)/营业收入 过低 → 过度依赖息差。
    利息净收入 = _num(structured, "利润表", "利息净收入")
    nir = (_ratio(营业收入 - 利息净收入, 营业收入)
           if (营业收入 is not None and 利息净收入 is not None) else None)
    nir = round(nir * 100, 4) if nir is not None else derived.get("非息收入占比")
    if nir is not None and nir < _非息占比_下限_pct:
        flags.append({"code": "非息收入占比过低", "命中": True, "严重度": "低",
                      "值": {"非息收入占比%": round(nir, 2), "下限%": _非息占比_下限_pct}})

    return flags
