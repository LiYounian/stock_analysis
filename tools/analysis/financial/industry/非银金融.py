"""非银金融(申万一级,券商/保险/多元金融)财报专家(P0 数值层)。
⚠️ 非投资建议;阈值/区间/权重均为工程占位,待策略提供者标定。

设计依据:参照 industry/银行.py 的**金融业特判范式**。券商/保险与制造业结构完全不同——
**无营业成本、无存货、高杠杆属常态**,通用五维(毛利率/存货周转/短债覆盖/资产负债率上限)
对非银**完全失效**,会系统性误杀。本模块:
  1. 覆写五维子指标 → 用金融口径 derived 键(营收增速_银行/总资产增速/净利率/成本收入比/ROA/ROE 等);
  2. 覆写五维权重 → 盈利质量与回报给高权(金融看真赚钱与股东回报,不看毛利);
  3. SKIP_FLAGS 跳掉对非银不适用的通用红旗(高负债/现金含量不足/短债覆盖不足/应收存货激增/毛利率跳升);
     ——注:KEY「非银金融」已在 config['金融业申万'] 内,analyzer 会自动按金融业跳过高负债类红旗,
        此处 SKIP 为并集冗余(双保险),并补跳毛利率类(非银无营业成本→无毛利率概念);
  4. extra_flags 用金融口径原始科目自算非银专属红旗(自营/投资依赖、浮盈质量、杠杆、成本收入比、扣非质量)。

业务口径:
  - 券商:收入结构 = 经纪(手续费及佣金)+ 投行(手续费及佣金)+ 自营(投资收益/公允价值变动)+ 利息;
    自营占比高 → 业绩随市场大幅波动("靠天吃饭"),杠杆放大波动。
  - 保险:准备金/内含价值/投资收益是核心,但**准备金/内含价值/新业务价值/偿付能力充足率属附注披露项**,
    akshare 三大表拿不到,相关维度/红旗用**可得科目代理**(投资收益/净利率 等)并在 NOTE 标注,真指标待补采。

阈值/区间/权重均为工程占位,注释注明"待标定"。纯函数、无状态、缺值→不命中/None,不抛异常。
"""
from __future__ import annotations

KEY = "非银金融"  # 申万一级规范名(必须正好这个字符串,否则路由不到)
NOTE = ("非银(券商/保险/多元金融)按金融业口径评分:无营业成本/无存货、高杠杆属常态,"
        "通用毛利率/存货周转/短债覆盖/资产负债率上限等对非银不适用已剔除;"
        "营收取『营业收入』(通用营收增速对非银常空);重点看 净利率/成本收入比/ROA/ROE/规模扩张;"
        "券商看自营(投资收益/公允价值变动)占比与杠杆,保险看投资收益;"
        "准备金/内含价值/新业务价值/偿付能力充足率属附注、akshare 暂未采集,相关红旗用可得科目代理,真指标待补采。")


def dimension_specs() -> dict:
    """覆写五维子指标区间(格式同 scoring.dimension_specs)。区间为工程占位,**待策略提供者标定**。
    键状态:营收增速_银行/总资产增速/成本收入比/ROA 等金融口径键 metrics 已产出(非金融票为空,非银为可得)。"""
    return {
        # 成长:营收(营业收入口径)+ 净利 + 规模扩张(杠杆/总资产)
        "成长": [("营业收入增速%", "营收增速_银行", -20, 30),   # 用营业收入,非营业总收入(非银 TOTAL_* 常空)
               ("归母净利增速%", "归母净利增速", -30, 40),
               ("总资产增速%", "总资产增速", -5, 25)],           # 规模/杠杆扩张
        # 质量(高权:金融看真赚钱):净利率 + 扣非占归母(防非经常/投资浮盈虚增)
        "质量": [("净利率%", "净利率", 0, 40),
               ("扣非占归母", "扣非占归母", 0.7, 1.0)],
        # 健康:非银高杠杆属常态(通用资产负债率上限剔除),区间**大幅放宽**仅识别极端;商誉(并购)反向
        "健康": [("资产负债率%(反向,仅识别极端)", "资产负债率", 92, 70),
               ("商誉占净资产%(反向)", "商誉占净资产", 50, 0)],
        # 运营:成本收入比(业管费/营收,反向,越低越好)——金融效率口径
        "运营": [("成本收入比%(反向)", "成本收入比", 60, 30)],
        # 回报(高权):股东与资产回报
        "回报": [("ROE%", "ROE", 0, 15),
               ("ROA%", "ROA", 0, 3)],
    }


def weights() -> dict | None:
    """覆写五维权重。金融看盈利质量与回报:质量、回报给高权;健康(杠杆)权重降(高杠杆是常态)。
    权重为工程占位,待标定。"""
    return {"成长": 0.15, "质量": 0.25, "健康": 0.15, "运营": 0.15, "回报": 0.30}


# 本行业不适用的通用红旗(制造业口径,对非银全失效)。KEY 已在 config['金融业申万'],
# analyzer 会自动按金融业跳过【高负债/现金含量不足/短债覆盖不足/应收存货激增】,此处显式列入为并集冗余,
# 并补跳【毛利率异常跳升】(非银无营业成本→无毛利率,该红旗无意义)。
SKIP_FLAGS = ["高负债", "现金含量不足", "短债覆盖不足", "应收存货激增", "毛利率异常跳升"]


# ── 专属红旗阈值(工程占位,待标定)──────────────────────────────────────
_HI_自营占比 = 0.50          # (投资收益+公允价值变动)/营业收入 高于此 → 自营依赖高,业绩随市大幅波动
_HI_浮盈占营业利润 = 0.30    # 公允价值变动收益/营业利润 高于此 → 未实现浮盈占比大,盈利质量存疑
_HI_杠杆倍数 = 12.0          # 资产总计/归母权益 高于此 → 杠杆过高(非银高杠杆常态,但过高放大风险)
_HI_成本收入比_pct = 60.0    # 业管费/营收 高于此 → 运营效率差(反向)
_LO_扣非占归母 = 0.6         # 扣非归母/归母 低于此 → 非经常损益(含处置/公允价值)撑利润,质量差


def _num(rec, *path):
    """安全取嵌套数值科目;任一层缺/非数 → None。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def _ratio(a, b):
    """a/b;a、b 任一 None 或 |b|≈0 → None。"""
    if a is None or b is None or abs(b) < 1e-9:
        return None
    return a / b


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """非银金融专属红旗(单期,纯函数,一切缺值→不命中,不抛)。金融口径,**不套制造业红旗**。
    阈值为工程占位,**待标定**。依赖同比历史/需补采监管比率(偿付能力/内含价值/准备金充足率)的红旗
    在单期接口下不判(缺数据不误杀),待衍生层/采集层补齐后接入。"""
    derived = derived or {}
    flags: list[dict] = []

    def add(code, sev, val):
        flags.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # 营业收入取金融口径(营业总收入 TOTAL_* 对非银常空,回退营业收入)
    营业收入 = (_num(structured, "利润表", "营业收入")
             or _num(structured, "利润表", "营业总收入"))
    营业利润 = _num(structured, "利润表", "营业利润")
    投资收益 = _num(structured, "利润表", "投资收益")
    公允价值变动 = _num(structured, "利润表", "公允价值变动收益")

    # ① 自营/投资依赖过高(业绩随市大幅波动)—— 中
    # 判据:(投资收益 + 公允价值变动收益) / 营业收入 偏高 → 券商自营/保险投资驱动,"靠天吃饭"、波动大。
    自营收入_parts = [x for x in (投资收益, 公允价值变动) if x is not None]
    自营收入 = sum(自营收入_parts) if 自营收入_parts else None
    r_zy = _ratio(自营收入, 营业收入)
    if r_zy is not None and r_zy > _HI_自营占比:
        add("自营依赖过高", "中",
            {"自营及投资收入": round(自营收入, 2), "营业收入": 营业收入, "占比": round(r_zy, 4),
             "上限": _HI_自营占比, "NOTE": "投资/自营驱动,业绩随市场大幅波动(靠天吃饭)"})

    # ② 浮盈质量存疑(公允价值变动占营业利润高)—— 中
    # 判据:公允价值变动收益 / 营业利润 偏高(且营业利润>0)→ 未实现浮盈撑利润,可持续性弱。
    r_fv = _ratio(公允价值变动, 营业利润)
    if (r_fv is not None and 营业利润 is not None and 营业利润 > 0
            and 公允价值变动 is not None and 公允价值变动 > 0 and r_fv > _HI_浮盈占营业利润):
        add("浮盈质量存疑", "中",
            {"公允价值变动收益": 公允价值变动, "营业利润": 营业利润, "占比": round(r_fv, 4),
             "上限": _HI_浮盈占营业利润, "NOTE": "未实现浮盈占比大,盈利质量/可持续性存疑"})

    # ③ 杠杆过高(权益乘数)—— 中
    # 判据:资产总计 / 归母权益 偏高。非银高杠杆是常态,但过高放大市场/流动性风险。
    资产总计 = _num(structured, "资产负债表", "资产总计")
    归母权益 = _num(structured, "资产负债表", "归母股东权益")
    杠杆 = _ratio(资产总计, 归母权益)
    if 杠杆 is not None and 杠杆 > _HI_杠杆倍数:
        add("杠杆过高", "中",
            {"权益乘数": round(杠杆, 2), "上限": _HI_杠杆倍数, "资产总计": 资产总计, "归母权益": 归母权益,
             "NOTE": "非银高杠杆属常态,过高放大市场/流动性风险"})

    # ④ 成本收入比走高(运营效率差)—— 低
    # 判据:业务及管理费 / 营业收入 偏高(自算优先,回退 derived);反向,越低越好。
    业管费 = _num(structured, "利润表", "业务及管理费")
    cir = _ratio(业管费, 营业收入)
    cir = round(cir * 100, 4) if cir is not None else derived.get("成本收入比")
    if cir is not None and cir > _HI_成本收入比_pct:
        add("成本收入比走高", "低",
            {"成本收入比%": round(cir, 2), "上限%": _HI_成本收入比_pct})

    # ⑤ 扣非质量差(非经常损益/浮盈撑利润)—— 中
    # 判据:扣非占归母 偏低,或归母为正而扣非为负 → 处置/公允价值等非经常项撑起利润,主业质量差。
    扣非占归母 = derived.get("扣非占归母")
    归母 = _num(structured, "利润表", "归母净利润")
    扣非 = _num(structured, "利润表", "扣非归母净利润")
    命中扣非 = False
    if 扣非占归母 is not None and 扣非占归母 < _LO_扣非占归母:
        命中扣非 = True
    elif (归母 is not None and 扣非 is not None and 归母 > 0 and 扣非 < 0):
        命中扣非 = True
    if 命中扣非:
        add("扣非质量差", "中",
            {"扣非占归母": (round(扣非占归母, 4) if 扣非占归母 is not None else None),
             "归母净利润": 归母, "扣非归母净利润": 扣非, "下限": _LO_扣非占归母,
             "NOTE": "非经常损益(含处置/公允价值)撑利润,主业盈利质量差"})

    return flags
