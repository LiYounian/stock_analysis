"""计算机(云计算 / 算力服务 / IDC)财报专家(P0 数值层)。

⚠️ 非投资建议;下列阈值/区间/权重均为**工程占位,待策略提供者标定**。

行业画像(见 docs/财报分析专家/计算机_算力服务_财报分析方案.md):
  计算机·云计算 内部高度分化——
    · 轻资产软件/SaaS:高毛利、重研发、项目制应收易膨胀;
    · 算力租赁/IDC:重资产、高资本开支/在建工程、折旧压制利润但现金流(理应)好。
  本模块核心防线是揪出"营收暴增但盈利/现金空心"的算力租赁类形态:
    ①营收暴增而净利率极低(贸易化/空心增长)
    ②应收增速远超营收(赊销撑收入,回款存疑)
    ③经营现金流/自由现金流为负(纸面利润,靠融资续命)
    ④资本开支超前于收入放量(产能空转)
  故评分**压低成长权重、重配质量(现金/净利率/毛利)与运营(应收)**。

契约:纯函数、无网络、无状态、不 import 其他行业模块;一切缺值 → 该项 None / 不命中,绝不抛异常。
单期口径:extra_flags 只拿到单期 derived/structured,无相邻期,故"研发骤降/在建工程增速"
这类同比量无法在此计算,改用已在 derived 里预算好的同比量(应收营收增速差 / 存货增速 / 合同负债环比)。
"""
from __future__ import annotations

KEY = "计算机"  # 申万一级规范名(必须正好这个字符串,否则路由不到)
NOTE = ("计算机·算力服务:重点看盈利质量而非营收增速——净利率是生死线、"
        "应收增速须≤营收、经营/自由现金流不能长期为负;成长权重下调,质量+运营为核心防线。"
        "研发费用率/在建工程增速需相邻期,单期红旗不判(留待正文/趋势层)。")

# ————————————————— 工程占位阈值(待策略提供者标定) —————————————————
# 标定 2026-08(feat/industry-threshold-calib):本行业池内财报样本薄(仅 6 票,不足稳健分布标定的
#   ≥8 票门槛),下列阈值**保留工程占位**、不硬编;待样本扩充后由 _calibration.py 重标。
_营收暴增_pct = 50.0        # 空心增长:营收增速阈值(高于此且净利率极低 → 疑贸易化)
_净利率极低_pct = 3.0       # 空心增长:净利率下限(算力租赁生死线,长期<3%=只走量不赚钱)
_应收超营收_pct = 30.0      # 应收激增:应收增速−营收增速 差值上限(赊销撑收入)
_存货超营收_pct = 40.0      # 存货激增:存货增速−营收增速 差值上限(GPU/服务器囤货)
_FCF比营收_下限 = -0.20     # 自由现金流大额为负:FCF/营收 低于此(烧钱扩张靠融资)
_capex比营收_上限 = 0.30    # 资本开支超前:capex/营收 高于此
_capex超前_营收增速_上限 = 10.0  # 且营收增速低于此(产能未兑现为收入)
_合同负债骤降_pct = -30.0   # 在手订单景气下滑:合同负债环比低于此


def dimension_specs() -> dict:
    """覆写五维子指标区间(格式同 scoring.dimension_specs:{维度: [(显示名, derived键, 0分端, 100分端)]})。
    反向指标 0分端 > 100分端。⚠️ 区间为工程占位待标定。

    设计要点(对齐方案 ④):
      · 成长:保留营收/扣非弹性但靠 weights 大幅减配,防"营收增速骗高分";
      · 质量:新增**净利率**为核心子指标,现金含量下限压到负(捕捉 CFO 为负),毛利率、扣非占比;
      · 健康:资产负债率(反向)+ 短债覆盖(自由现金流为绝对额、非尺度不变,不入线性打分,改由红旗发声);
      · 运营:应收周转天数(反向)+ 应收营收增速差(反向,直击赊销冲收入);
      · 回报:ROE 放宽下限(早期可负)。
    """
    return {
        "成长": [("营收增速%", "营收增速", -20, 60),
               ("扣非净利增速%", "扣非净利增速", -20, 60)],
        "质量": [("净利率%", "净利率", 0, 15),
               ("现金含量 CFO/归母净利", "现金含量_CFO比净利", -0.5, 1.2),
               ("毛利率%", "毛利率", 0, 40),
               ("扣非占归母", "扣非占归母", 0.5, 1.0)],
        "健康": [("资产负债率%(反向)", "资产负债率", 75, 30),
               ("短债覆盖", "短债覆盖", 0, 2)],
        "运营": [("应收周转天数(反向)", "应收周转天数", 180, 30),
               ("应收营收增速差pct(反向)", "应收营收增速差", 30, -10)],
        "回报": [("ROE%", "ROE", -5, 15)],
    }


def weights() -> dict | None:
    """覆写五维权重(方案 ④:减配成长、重配质量+运营)。⚠️ 权重为工程占位待标定。"""
    return {"成长": 0.15, "质量": 0.35, "健康": 0.15, "运营": 0.20, "回报": 0.15}


# 本行业不适用的**通用红旗**:应收存货激增改用行业专属(应收激增超营收 / 存货激增)口径替代,
# 阈值更贴合算力租赁的赊销/囤货形态,且避免与专属红旗对同一现象重复扣分。
SKIP_FLAGS = ["应收存货激增"]


def _num(rec: dict | None, *path: str):
    """安全取嵌套数值科目:_num(structured, '现金流量表', '经营活动现金流量净额');任一层缺/非数 → None。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def _sev(name: str, sev: str, val: dict, hit: bool) -> dict:
    return {"code": name, "命中": hit, "严重度": sev, "值": val}


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """计算机·算力服务专属红旗。返回 [{code,命中,严重度,值}, ...],仅命中项会被并入结果。
    一切缺值 → 该条不命中,不抛异常。⚠️ 阈值工程占位待标定。

    专属红旗(7 条):
      1. 空心增长(高):营收增速>50% 且 净利率<3% —— 行云科技类核心红旗(暴增但贸易化)。
      2. 应收激增超营收(高):应收增速−营收增速 > 30pct —— 赊销撑收入,回款质量存疑。
      3. 经营现金流为负(高):CFO<0 且 归母净利润>0 —— 利润是纸面的。
      4. 自由现金流大额为负(中):(CFO−capex)/营收 < -20% —— 烧钱扩张靠融资续命。
      5. 存货激增(中):存货增速−营收增速 > 40pct —— GPU/服务器囤货或滞销。
      6. 资本开支超前收入(中):capex/营收>30% 且 营收增速<10% —— 产能空转风险。
      7. 合同负债骤降(低):合同负债环比 < -30% —— 在手订单/景气下滑。
    """
    derived = derived or {}
    structured = structured or {}
    out: list[dict] = []

    营收增速 = derived.get("营收增速")
    净利率 = derived.get("净利率")
    应收营收增速差 = derived.get("应收营收增速差")
    存货增速 = derived.get("存货增速")
    合同负债环比 = derived.get("合同负债环比")

    cfo = _num(structured, "现金流量表", "经营活动现金流量净额")
    capex = _num(structured, "现金流量表", "购建固定资产无形资产等支付现金")
    归母净利润 = _num(structured, "利润表", "归母净利润")
    营收_abs = _num(structured, "利润表", "营业总收入") or _num(structured, "利润表", "营业收入")

    # 1. 空心增长:营收暴增但净利率极低(贸易化/转售算力,收入"看着增,钱没赚到")
    if 营收增速 is not None and 净利率 is not None:
        if 营收增速 > _营收暴增_pct and 净利率 < _净利率极低_pct:
            out.append(_sev("空心增长", "高",
                            {"营收增速": 营收增速, "净利率": 净利率,
                             "营收阈值": _营收暴增_pct, "净利率下限": _净利率极低_pct}, True))

    # 2. 应收激增超营收:应收增速远超营收(赊销撑收入,头号回款雷)
    if 应收营收增速差 is not None and 应收营收增速差 > _应收超营收_pct:
        out.append(_sev("应收激增超营收", "高",
                        {"应收营收增速差pct": round(应收营收增速差, 4), "上限pct": _应收超营收_pct}, True))

    # 3. 经营现金流为负:CFO<0 但归母为正 → 利润未变现(纸面利润)
    if cfo is not None and 归母净利润 is not None and cfo < 0 and 归母净利润 > 0:
        out.append(_sev("经营现金流为负", "高",
                        {"经营活动现金流量净额": cfo, "归母净利润": 归母净利润}, True))

    # 4. 自由现金流大额为负:(CFO−capex)/营收 低于下限(重资产烧钱靠融资续命)
    if cfo is not None and capex is not None and 营收_abs:
        fcf = cfo - capex
        fcf_ratio = fcf / 营收_abs
        if fcf_ratio < _FCF比营收_下限:
            out.append(_sev("自由现金流大额为负", "中",
                            {"自由现金流": fcf, "FCF占营收": round(fcf_ratio, 4),
                             "下限": _FCF比营收_下限}, True))

    # 5. 存货激增:存货增速远超营收(硬件囤货/滞销)
    if 存货增速 is not None and 营收增速 is not None:
        gap = 存货增速 - 营收增速
        if gap > _存货超营收_pct:
            out.append(_sev("存货激增", "中",
                            {"存货增速": 存货增速, "营收增速": 营收增速,
                             "差值pct": round(gap, 4), "上限pct": _存货超营收_pct}, True))

    # 6. 资本开支超前收入:capex 占营收高 但营收未放量(IDC/算力产能空转)
    if capex is not None and 营收_abs and 营收增速 is not None:
        capex_ratio = capex / 营收_abs
        if capex_ratio > _capex比营收_上限 and 营收增速 < _capex超前_营收增速_上限:
            out.append(_sev("资本开支超前收入", "中",
                            {"capex占营收": round(capex_ratio, 4), "营收增速": 营收增速,
                             "capex占比上限": _capex比营收_上限,
                             "营收增速上限": _capex超前_营收增速_上限}, True))

    # 7. 合同负债骤降:环比大幅下滑(在手订单/景气下行)
    if 合同负债环比 is not None and 合同负债环比 < _合同负债骤降_pct:
        out.append(_sev("合同负债骤降", "低",
                        {"合同负债环比pct": round(合同负债环比, 4), "下限pct": _合同负债骤降_pct}, True))

    return out
