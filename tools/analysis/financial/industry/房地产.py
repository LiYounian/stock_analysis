"""房地产(申万一级)财报专家(P0 数值层)。
⚠️ 非投资建议;阈值/区间/权重均为工程占位,待策略提供者标定。

行业画像:高杠杆、预售制、长周期结算的资金密集行业,债务安全是命门。
  - 预收/合同负债 = 销售锁定:期房预售款计入合同负债(及预收账款),是**已售未结**的未来营收蓄水池,
    高/环比升 → 销售去化好、业绩有保障;环比走弱 → 销售遇冷预警。
  - 高负债是**行业特性,不当异常**:地产天然高资产负债率(拿地/开发全靠融资),通用「高负债」红旗对
    地产**系统性误杀**,故 SKIP;改用**三道红线专项红旗**(净负债率/现金短债比/剔预资产负债率)承接
    真实债务风险——这是地产监管框架的核心口径,比通用资产负债率更能识别流动性危机。
  - 存货去化(开发产品周转):地产存货=在建/待售开发产品,周转天然极慢(运营维区间已放宽);
    存货增速远超营收=去化放缓/累库,单列专属红旗。
  - 少数股东损益占比 = 明股实债信号:若少数股东**权益占比高**但**损益占比显著偏低**,常是"名为股权、
    实为债权"的表外加杠杆(小股东只出资不分利,实质是刚兑负债),单列"明股实债嫌疑"红旗。
  - 经营现金流:拿地扩张期 CFO 常为负(大额购地),但持续净流出叠加高负债=资金链风险。

三道红线口径(全部可由已采集科目自算):
  ① 净负债率 = (有息负债 − 货币资金) / 归母权益,红线 > 100%
  ② 现金短债比 = 货币资金 / 短期有息负债,红线 < 1.0
  ③ 剔预资产负债率 = (负债合计 − 预收账款 − 合同负债) / (资产总计 − 预收账款 − 合同负债),红线 > 70%
  踩线条数 → 红档(3)/橙档(2)/黄档(1)/绿档(0),严重度随档位升。

阈值/区间/权重均为工程占位,注释注明"待标定"。纯函数、无状态、缺值→不命中/None,不抛异常。
"""
