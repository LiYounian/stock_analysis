# 本行业不适用/会误杀的通用红旗:
#   高负债 —— 地产拿地/开发全靠融资,高资产负债率是**行业特性**,通用版会系统性误杀,SKIP;
#            真实债务风险改由**三道红线专项红旗**(净负债率/现金短债比/剔预资产负债率)承接。
SKIP_FLAGS = ["高负债"]


# ── 专属红旗阈值(工程占位,待标定)──────────────────────────────────────
# 标定 2026-08(feat/industry-threshold-calib):本行业池内财报样本薄(仅 5 票,不足稳健分布标定的
#   ≥8 票门槛)。**三条红线为监管硬口径(非拍脑袋占位)保留原值**;其余占位阈值待样本扩充后重标。
_红线_净负债率_pct = 100.0      # (有息负债−货币资金)/归母权益 > 100% → 踩线
_红线_现金短债比 = 1.0          # 货币资金/短期有息负债 < 1.0 → 踩线
_红线_剔预资产负债率_pct = 70.0  # (负债−预收−合同负债)/(资产−预收−合同负债) > 70% → 踩线
_档位严重度 = {3: "高", 2: "高", 1: "中", 0: "低"}  # 踩线条数→严重度(0 档不发声)
_LO_合同负债环比 = -15.0        # 合同负债(预收)环比 低于此 pct → 销售去化遇冷
_存货超营收增速_GAP = 20.0      # 存货增速 领先 营收增速 超此 pct → 去化放缓/累库
_HI_少数股东权益占比 = 0.30     # 少数股东权益/股东权益合计 高于此(且损益占比显著更低)→ 明股实债嫌疑
_明股实债_损益权益比 = 0.5      # 少数股东损益占比 < 权益占比×此系数 → 出资不分利,疑似明股实债


def _num(rec, *path):
    """安全取嵌套数值科目;任一层缺/非数 → None。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def _ratio(a, b):
    """a/b;a、b 任一 None 或 |b|≈0 → None。"""
    if a is None or b is None or abs(b) < 1e-9:
        return None
    return a / b


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """房地产专属红旗。返回 [{code,命中,严重度,值}, ...](调用方仅并入 命中=True 的)。
    单期、纯函数,一切缺值→不命中,不抛异常。阈值为工程占位,**待标定**。"""
    derived = derived or {}
    structured = structured if isinstance(structured, dict) else {}
    利润表 = structured.get("利润表", {}) if isinstance(structured.get("利润表"), dict) else {}
    现金流量表 = (structured.get("现金流量表", {})
              if isinstance(structured.get("现金流量表"), dict) else {})

    flags: list[dict] = []

    def add(code, sev, val):
        flags.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # ── 三道红线专项(逐条判踩线,汇总档位)────────────────────────────
    货币资金 = _num(structured, "资产负债表", "货币资金")
    归母权益 = _num(structured, "资产负债表", "归母股东权益")
    负债合计 = _num(structured, "资产负债表", "负债合计")
    资产总计 = _num(structured, "资产负债表", "资产总计")
    预收账款 = _num(structured, "资产负债表", "预收账款") or 0.0
    合同负债 = _num(structured, "资产负债表", "合同负债") or 0.0
    短期借款 = _num(structured, "资产负债表", "短期借款") or 0.0
    一年内到期 = _num(structured, "资产负债表", "一年内到期非流动负债") or 0.0
    有息负债 = derived.get("有息负债")
    短期有息负债 = 短期借款 + 一年内到期

    踩线明细 = {}
    踩线数 = 0

    # ① 净负债率 = (有息负债 − 货币资金) / 归母权益
    净负债率 = (_ratio(有息负债 - 货币资金, 归母权益)
             if (有息负债 is not None and 货币资金 is not None and 归母权益 is not None) else None)
    if 净负债率 is not None:
        净负债率_pct = round(净负债率 * 100, 2)
        踩 = 净负债率_pct > _红线_净负债率_pct
        踩线明细["净负债率%"] = {"值": 净负债率_pct, "红线%": _红线_净负债率_pct, "踩线": 踩}
        踩线数 += int(踩)

    # ② 现金短债比 = 货币资金 / 短期有息负债(=derived.短债覆盖;此处独立自算保证口径透明)
    现金短债比 = _ratio(货币资金, 短期有息负债) if 短期有息负债 > 1e-9 else None
    if 现金短债比 is not None:
        踩 = 现金短债比 < _红线_现金短债比
        踩线明细["现金短债比"] = {"值": round(现金短债比, 4), "红线": _红线_现金短债比, "踩线": 踩}
        踩线数 += int(踩)

    # ③ 剔预资产负债率 = (负债 − 预收 − 合同负债) / (资产 − 预收 − 合同负债)
    分子 = (负债合计 - 预收账款 - 合同负债) if 负债合计 is not None else None
    分母 = (资产总计 - 预收账款 - 合同负债) if 资产总计 is not None else None
    剔预 = _ratio(分子, 分母)
    if 剔预 is not None:
        剔预_pct = round(剔预 * 100, 2)
        踩 = 剔预_pct > _红线_剔预资产负债率_pct
        踩线明细["剔预资产负债率%"] = {"值": 剔预_pct, "红线%": _红线_剔预资产负债率_pct, "踩线": 踩}
        踩线数 += int(踩)

    # 汇总档位:仅当至少踩 1 条才发声;档位越高严重度越高
    if 踩线明细 and 踩线数 >= 1:
        档位 = {3: "红档", 2: "橙档", 1: "黄档"}.get(踩线数, "绿档")
        add("三道红线踩线", _档位严重度.get(踩线数, "中"),
            {"踩线条数": 踩线数, "档位": 档位, "明细": 踩线明细,
             "NOTE": "净负债率>100%/现金短债比<1/剔预资产负债率>70% 逐条判定"})

    # ── 明股实债嫌疑(少数股东出资不分利)──────────────────────────────
    # 少数股东损益 = 净利润 − 归母净利润;少数股东权益 = 股东权益合计 − 归母股东权益。
    # 特征:权益占比高(小股东大额出资)但损益占比显著偏低(几乎不分利)→ 名股实债的表外刚兑负债。
    净利润 = 利润表.get("净利润")
    归母净利 = 利润表.get("归母净利润")
    股东权益合计 = _num(structured, "资产负债表", "股东权益合计")
    if (isinstance(净利润, (int, float)) and isinstance(归母净利, (int, float))
            and 归母权益 is not None and 股东权益合计 is not None and abs(股东权益合计) > 1e-9):
        少数权益 = 股东权益合计 - 归母权益
        权益占比 = 少数权益 / 股东权益合计
        损益占比 = ((净利润 - 归母净利) / 净利润) if abs(净利润) > 1e-9 else None
        if (权益占比 > _HI_少数股东权益占比 and 损益占比 is not None
                and 损益占比 < 权益占比 * _明股实债_损益权益比):
            add("明股实债嫌疑", "中",
                {"少数股东权益占比": round(权益占比, 4), "少数股东损益占比": round(损益占比, 4),
                 "权益阈": _HI_少数股东权益占比,
                 "NOTE": "小股东大额出资却几乎不分利,疑似名股实债的表外刚兑负债"})

    # ── 存货去化放缓(开发产品累库)──────────────────────────────────
    存货增速 = derived.get("存货增速")
    营收增速 = derived.get("营收增速")
    if (存货增速 is not None and 营收增速 is not None
            and 存货增速 > 0 and (存货增速 - 营收增速) > _存货超营收增速_GAP):
        add("去化放缓", "中",
            {"存货增速": 存货增速, "营收增速": 营收增速, "差值pct": round(存货增速 - 营收增速, 4),
             "NOTE": "开发产品存货增速显著超营收=去化放缓/累库"})

    # ── 销售遇冷(合同负债/预收环比走弱)────────────────────────────
    合同负债环比 = derived.get("合同负债环比")
    if 合同负债环比 is not None and 合同负债环比 < _LO_合同负债环比:
        add("销售去化遇冷", "中",
            {"合同负债环比%": round(合同负债环比, 4), "下限%": _LO_合同负债环比,
             "NOTE": "预收/合同负债(已售未结)环比走弱,销售转冷"})

    # ── 经营现金流为负(拿地扩张/销售遇冷,叠加高负债=资金链风险)──────
    CFO = 现金流量表.get("经营活动现金流量净额")
    if (isinstance(归母净利, (int, float)) and 归母净利 > 0
            and isinstance(CFO, (int, float)) and CFO < 0):
        add("经营现金流为负", "中", {"归母净利润": 归母净利, "经营活动现金流量净额": CFO,
                              "NOTE": "账面盈利却经营现金净流出,叠加高负债需警惕资金链"})

    return flags
