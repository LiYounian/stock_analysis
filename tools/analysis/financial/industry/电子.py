"""电子行业财报专家(P0 数值层)。⚠️ 非投资建议;阈值为工程占位待标定。

电子/科技制造 = 技术密集 + 资本密集 + 强周期 三重叠加,财报画像与消费/金融差异极大:
  - 技术密集 → 研发费用率是核心质地(质量维加权、专属红旗盯"研发占比过低");
  - 强周期 → 毛利率与存货大起大落(毛利率区间上移放宽、运营维加权、专属红旗盯"存货高企");
  - 资本密集 → 在建工程/固定资产大额扩产,错配下行周期即产能过剩(专属红旗盯"扩产错配")。

覆写点见 docs/财报分析专家/电子_半导体材料PCB光学_财报分析方案.md §④(区间/权重)、§③(专属红旗)。
纯函数、无状态、无网络;一切取值/除法缺失 → 该项 None / 不命中,绝不抛异常。
"""
from __future__ import annotations

KEY = "电子"                                  # 申万一级规范名(路由键,必须正好这个字符串)
NOTE = ("电子/科技制造:重研发(研发费用率)、强周期(存货/毛利率大起大落)、重资产扩产(在建工程/固定资产)。"
        "毛利率因细分(光学/陶瓷/PCB/硅片)跨度大用统一放宽区间;季报比率未年化,只做趋势/同业相对。")


def dimension_specs() -> dict:
    """覆写五维子指标区间(0分端 → 100分端;反向指标 lo>hi)。格式同 scoring.dimension_specs。

    三处强化(见方案 §④):质量维加"研发费用率"、毛利率区间上移放宽(10→55,跨半导体材料~光学)、
    运营维存货周转略快;成长维两端放宽(电子波动大);健康维负债率区间略放宽(重资产)。
    ⚠️ 所有区间为工程占位/AI 建议默认,待策略提供者标定(M3)。"""
    return {
        # 成长:电子波动大,营收/扣非增速两端放宽
        "成长": [("营收增速%", "营收增速", -25, 45),
               ("扣非净利增速%", "扣非净利增速", -30, 50)],
        # 质量:加研发费用率(技术密集核心);毛利率中枢上移放宽
        "质量": [("现金含量 CFO/归母净利", "现金含量_CFO比净利", 0, 1.2),
               ("扣非占归母", "扣非占归母", 0, 1.0),
               ("毛利率%", "毛利率", 10, 55),
               ("研发费用率%", "研发费用率", 1, 8)],
        # 健康:重资产,负债率区间略放宽
        "健康": [("资产负债率%(反向)", "资产负债率", 75, 30),
               ("短债覆盖", "短债覆盖", 0, 2),
               ("商誉占净资产%(反向)", "商誉占净资产", 50, 0)],
        # 运营:电子存货周转比通用略快
        "运营": [("应收周转天数(反向)", "应收周转天数", 180, 45),
               ("存货周转天数(反向)", "存货周转天数", 240, 60)],
        # 回报:ROE 季报未年化,做趋势/相对
        "回报": [("ROE%", "ROE", 0, 12)],
    }


def weights() -> dict | None:
    """覆写五维权重。电子核心区分度在"技术领先(研发/毛利率)"与"存货周期(减值/周转)",
    故 质量维 1.2、运营维 1.1 略加权,其余等权。⚠️ 工程占位待标定,提供者可覆盖。"""
    return {"成长": 1.0, "质量": 1.2, "健康": 1.0, "运营": 1.1, "回报": 1.0}


# 本行业不适用的通用红旗:电子(制造业)不做金融业那种大规模跳过——
# 高负债/存货对制造业适用,应收存货激增亦保留(方案 §③:电子加权关注)。故为空。
SKIP_FLAGS: list[str] = []


# ── 专属红旗阈值(工程占位,待策略提供者标定 M3)──────────────────────────
_存货增速超营收_pct = 15.0          # 存货增速 − 营收增速 > 此值 → 存货高企嫌疑
_毛利率同比下滑_pct = -3.0          # 毛利率同比升 < 此值(即下滑>3pct)→ 联动加重
_毛利率连续下滑_pct = -5.0          # 毛利率同比升 < 此值(累计降幅>5pct)→ 毛利率持续下滑
_研发费用率下限_pct = 3.0           # 研发费用率 < 此值(制造密集口径)→ 研发占比过低
_减值损失占营收_pct = 2.0           # |资产减值损失| / 营收 > 此值 → 存货减值高企(仅年报/半报)
_在建占固定资产_下限 = 0.35         # 在建工程 / 固定资产 > 此值 → 扩产激进
_扩产错配营收增速_pct = 0.0         # 且 营收增速 < 此值(走弱/负增)→ 扩产错配
_年报半报 = {"年报", "半年报", "中报"}  # 减值明细仅年报/半报披露,季报为 NaN 不判


def _num(rec: dict | None, *path: str):
    """安全取嵌套数值科目:_num(rec, '资产负债表', '存货');任一层缺/非数 → None。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """电子专属红旗。返回 [{code,命中,严重度,值}, ...];只有 命中=True 的会并入结果。

    一切缺值 → 不命中,不抛异常。所有阈值为工程占位待标定。"""
    flags: list[dict] = []
    derived = derived or {}
    structured = structured or {}

    营收增速 = derived.get("营收增速")
    存货增速 = derived.get("存货增速")
    毛利率同比升 = derived.get("毛利率同比升")   # analyzer 注入(可选);缺失 → 相关联动不加重
    研发费用率 = derived.get("研发费用率")

    # 1) 存货高企:存货增速远超营收(周期先行信号,易减值)。若叠加毛利率同比下滑 → 升级为「高」。
    if 营收增速 is not None and 存货增速 is not None and (存货增速 - 营收增速) > _存货增速超营收_pct:
        叠加下滑 = 毛利率同比升 is not None and 毛利率同比升 < _毛利率同比下滑_pct
        flags.append({
            "code": "存货高企",
            "命中": True,
            "严重度": "高" if 叠加下滑 else "中",
            "值": {"存货增速": 存货增速, "营收增速": 营收增速,
                  "差值pct": round(存货增速 - 营收增速, 4),
                  "毛利率同比升pct": (round(毛利率同比升, 4) if 毛利率同比升 is not None else None)},
        })

    # 2) 毛利率持续下滑:同比累计降幅 > 5pct(价格战/产品老化/成本上行)。需 analyzer 注入毛利率同比升。
    if 毛利率同比升 is not None and 毛利率同比升 < _毛利率连续下滑_pct:
        flags.append({
            "code": "毛利率持续下滑",
            "命中": True,
            "严重度": "中",
            "值": {"毛利率同比升pct": round(毛利率同比升, 4), "阈值pct": _毛利率连续下滑_pct},
        })

    # 3) 研发投入骤降 / 研发占比过低:研发费用率 < 3%(技术密集行业里明显偏低,失去代际领先风险)。
    if 研发费用率 is not None and 研发费用率 < _研发费用率下限_pct:
        flags.append({
            "code": "研发占比过低",
            "命中": True,
            "严重度": "中",
            "值": {"研发费用率": round(研发费用率, 4), "下限pct": _研发费用率下限_pct},
        })

    # 4) 存货减值高企:|资产减值损失| / 营收 > 2%(存货跌价/技术迭代)。
    #    减值明细仅年报/半报有值,季报为 NaN → 限定披露期,避免季报误杀。
    #    口径:by_report 接口减值列常映射到 *_INCOME(负值=损失),故取绝对值作损失额代理。
    report_type = structured.get("report_type")
    if report_type is None or report_type in _年报半报:
        营收_abs = _num(structured, "利润表", "营业总收入") or _num(structured, "利润表", "营业收入")
        减值 = _num(structured, "利润表", "资产减值损失")
        if 减值 is not None and 营收_abs:
            损失额 = abs(减值)
            占比pct = 损失额 / 营收_abs * 100
            if 占比pct > _减值损失占营收_pct:
                flags.append({
                    "code": "存货减值高企",
                    "命中": True,
                    "严重度": "中",
                    "值": {"资产减值损失": 减值, "占营收pct": round(占比pct, 4),
                          "阈值pct": _减值损失占营收_pct},
                })

    # 5) 扩产错配:在建工程/固定资产偏高(扩产激进)且营收走弱/负增 → 投产即过剩,折旧压未来利润。
    #    单期口径:用 在建工程/固定资产 比值作扩产强度代理(无未来函数,不需前期数据)。
    在建工程 = _num(structured, "资产负债表", "在建工程")
    固定资产 = _num(structured, "资产负债表", "固定资产")
    if (在建工程 is not None and 固定资产 and 固定资产 > 0
            and 营收增速 is not None):
        在建占比 = 在建工程 / 固定资产
        if 在建占比 > _在建占固定资产_下限 and 营收增速 < _扩产错配营收增速_pct:
            flags.append({
                "code": "扩产错配",
                "命中": True,
                "严重度": "中",
                "值": {"在建工程占固定资产": round(在建占比, 4), "营收增速": 营收增速,
                      "在建占比下限": _在建占固定资产_下限},
            })

    return flags
