def dimension_specs() -> dict:
    """覆写五维子指标区间(格式同 scoring.dimension_specs)。区间为工程占位,**待策略提供者标定**。"""
    return {
        # 成长(压权承接):周期弹性大但上端不拉太高——防止把顶部高增当高分(防追顶)
        "成长": [("营收增速%", "营收增速", -30, 40),
               ("归母净利增速%", "归母净利增速", -50, 60),
               ("扣非净利增速%", "扣非净利增速", -50, 60)],
        # 质量(加权:周期看真赚钱):毛利率区间偏中(化工 10%~30%);扣非占归母防非经常;现金含量看背离
        "质量": [("毛利率%", "毛利率", 10, 30),
               ("扣非占归母", "扣非占归母", 0.6, 1.0),
               ("现金含量 CFO/归母", "现金含量_CFO比净利", 0, 1.2)],
        # 健康:重资产高杠杆常态,资产负债率反向区间放宽(承接不 skip 的高负债)
        "健康": [("资产负债率%(反向)", "资产负债率", 70, 40),
               ("短债覆盖", "短债覆盖", 0, 1.5)],
        # 运营:存货受价格扰动大(周转天数波动),给合理宽度;应收账期
        "运营": [("应收周转天数(反向)", "应收周转天数", 120, 40),
               ("存货周转天数(反向)", "存货周转天数", 150, 50)],
        "回报": [("ROE%", "ROE", -5, 18)],
    }


