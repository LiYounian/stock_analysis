"""食品饮料(申万一级,含白酒/啤酒/调味品/乳品/休闲食品)财报专家(P0 数值层)。
⚠️ 非投资建议;阈值/区间/权重均为工程占位,待策略提供者标定。

行业画像:强品牌、高毛利、现金牛,**高端白酒(看预收/提价/品牌溢价)与大众食品(看周转/成本)两套逻辑**。
  - 预收账款 / 合同负债 = 白酒渠道景气**领先指标**:经销商打款意愿强 → 合同负债高企/环比增(景气上行);
    合同负债环比骤降 → 渠道去库存/动销转弱,是白酒最灵敏的先行信号。
  - 经销商压货:公司向渠道压货冲收入 → 应收账款 / 存货 增速远超营收增速,表内积压而非真实动销,单列红旗。
  - 毛利率与品牌溢价:高端白酒毛利 70%+、调味品/乳品次之;毛利率下滑 = 提价乏力 / 促销加码 / 品牌溢价流失。
  - 现金流质量:消费股**本应经营现金流充沛**(先款后货、账期短);归母正而 CFO 负 或 现金含量持续偏低 =
    与消费股财务特征**背离**,是利润质量的强红旗(比制造业更严格对待)。
  - 高端提价周转慢、大众食品薄利快转,两类周转天数差异大,区间给合理宽度。
  - **白酒预收(合同负债)计入负债会推高资产负债率**,但这是渠道景气(客户预付货款)而非偿债风险,通用
    「高负债」红旗会**系统性误杀白酒**,故 SKIP,交由区间/专属信号处理。

阈值/区间/权重均为工程占位,注释注明"待标定"。纯函数、无状态、缺值→不命中/None,不抛异常。
"""
from __future__ import annotations

KEY = "食品饮料"  # 申万一级规范名(必须正好这个字符串,否则路由不到)
NOTE = ("食品饮料强品牌高毛利现金牛:白酒渠道景气看**预收/合同负债环比**(领先指标,骤降=动销转弱);"
        "经销商压货看应收/存货增速超营收、毛利看品牌溢价、现金流看是否充沛(消费股背离=强红旗);"
        "高端白酒看预收/提价、大众食品看周转/成本;"
        "预收(合同负债)计入负债推高资产负债率属渠道景气非偿债风险,通用『高负债』已 SKIP 防误杀白酒。")


def dimension_specs() -> dict:
    """覆写五维子指标区间(格式同 scoring.dimension_specs):{维度: [(显示名, derived键, 0分端, 100分端)]}。
    反向指标 0分端 > 100分端。区间为工程占位,**待策略提供者标定**。"""
    return {
        # 成长:高端白酒稳健,大众食品温和;扣非弱化一次性收益
        "成长": [("营收增速%", "营收增速", -10, 40),
               ("归母净利增速%", "归母净利增速", -15, 45),
               ("扣非净利增速%", "扣非净利增速", -15, 45)],
        # 质量(最重):食饮天然高毛利(白酒 70%+),区间上移;扣非占归母防一次性;
        #   现金含量下端上移(消费股本应现金充沛,弱现金流即扣分)
        "质量": [("毛利率%", "毛利率", 25, 80),
               ("扣非占归母", "扣非占归母", 0.7, 1.0),
               ("现金含量 CFO/归母", "现金含量_CFO比净利", 0.3, 1.3)],
        # 健康:食饮低杠杆现金厚(预收推高负债率但非风险),资产负债率反向按常规;短债覆盖看现金厚度
        "健康": [("资产负债率%(反向)", "资产负债率", 60, 25),
               ("短债覆盖", "短债覆盖", 0.5, 3.0)],
        # 运营:高端提价周转慢、大众薄利快转,区间给宽度;应收账期短(现款为主)
        "运营": [("应收周转天数(反向)", "应收周转天数", 60, 10),
               ("存货周转天数(反向)", "存货周转天数", 300, 80)],
        # 回报(提权):品牌溢价→高 ROE 现金牛,是消费股核心
        "回报": [("ROE%", "ROE", 5, 25)],
    }


def weights() -> dict | None:
    """覆写五维权重。质量最重(毛利/现金决定品牌真赚钱),回报提权(现金牛 ROE)。待标定。"""
    return {"成长": 0.20, "质量": 0.30, "健康": 0.10, "运营": 0.15, "回报": 0.25}


# 本行业不适用/会误杀的通用红旗:
#   高负债 —— 白酒预收(合同负债)计入负债推高资产负债率,属渠道景气(客户预付)而非偿债风险,
#   通用「高负债」会系统性误杀白酒,SKIP,交由区间/专属渠道信号处理。
SKIP_FLAGS = ["高负债"]


def _ratio(a, b):
    """a/b;a、b 任一 None 或 |b|≈0 → None。"""
    if a is None or b is None or abs(b) < 1e-9:
        return None
    return a / b


# ── 专属红旗阈值 ──────────────────────────────────────────────────────
# 标定 2026-08(feat/industry-threshold-calib):食品饮料 12 票 / 144 报告期(2023Q3~2026Q2,
#   时序严格锚披露日),分布锚定(见 _calibration.py)。**注意:本行业毛利率双峰**(白酒高毛利 vs
#   大众品低毛利),行业池化分位混合两群,故仅纠正明显泛滥的毛利率阈值,GAP 类波动大保留不收紧。
_LO_合同负债环比 = -15.0      # 合同负债环比<此→白酒渠道景气转弱。分布 p10≈-37,命中≈32%,保留(合同负债波动大)
_应收超营收增速_GAP = 20.0    # 应收增速领先营收>此pct→经销商压货。分布 p75=40/p85=66,命中≈38%(偏噪),暂保留观察
_存货超营收增速_GAP = 25.0    # 存货增速领先营收>此pct→压货/动销转弱。分布 p80≈24/p85=33,命中≈20%(尾部),保留
_LO_毛利率 = 18.0            # [标定 25.0→18.0] 毛利<此→提价乏力/溢价流失。原25≈行业中位(命中40%=泛滥,把大众品
                            #   常态低毛利误当红旗);18≈p22,只逮真·低毛利尾部(分布 p10=8.98/p25=18.6/p50=29.8)
_LO_现金含量 = 0.5           # CFO/归母<此(且归母>0)→与消费股现金充沛背离。命中≈34%,保留(消费股本应现金厚,高标合理)


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """食品饮料专属红旗。返回 [{code,命中,严重度,值}, ...](调用方仅并入 命中=True 的)。
    单期、纯函数,一切缺值→不命中,不抛异常。阈值为工程占位,**待标定**。"""
    derived = derived or {}
    利润表 = (structured or {}).get("利润表", {}) if isinstance(structured, dict) else {}
    资产负债表 = (structured or {}).get("资产负债表", {}) if isinstance(structured, dict) else {}
    现金流量表 = (structured or {}).get("现金流量表", {}) if isinstance(structured, dict) else {}

    flags: list[dict] = []

    def add(code, sev, val):
        flags.append({"code": code, "命中": True, "严重度": sev, "值": val})

    营收增速 = derived.get("营收增速")

    # ① 渠道景气转弱(预收/合同负债环比下滑)—— 高【白酒最灵敏的领先信号】
    # 判据:合同负债(预收)环比 显著负增 → 经销商打款意愿降,动销/去库存转弱。
    # 说明:白酒尤为关键;大众食品预收占比小,该信号弱化但仍适用。阈值为工程占位,待标定。
    合同负债环比 = derived.get("合同负债环比")
    if 合同负债环比 is not None and 合同负债环比 < _LO_合同负债环比:
        add("渠道景气转弱", "高",
            {"合同负债环比": round(合同负债环比, 4), "下限pct": _LO_合同负债环比,
             "NOTE": "预收(合同负债)是白酒渠道景气领先指标,环比骤降=打款意愿降/动销转弱"})

    # ② 经销商压货(应收/存货增速超营收)—— 中
    # 判据:应收增速 或 存货增速 领先营收增速超阈值且在增 → 向渠道压货冲收入,表内积压非真实动销。
    应收增速 = derived.get("应收增速")
    存货增速 = derived.get("存货增速")
    hit_压货 = False
    val_压货: dict = {"NOTE": "向渠道压货冲收入,表内积压而非真实动销"}
    if (应收增速 is not None and 营收增速 is not None
            and 应收增速 > 0 and (应收增速 - 营收增速) > _应收超营收增速_GAP):
        hit_压货 = True
        val_压货.update({"应收增速": 应收增速, "营收增速": 营收增速,
                        "应收超营收pct": round(应收增速 - 营收增速, 4)})
    if (存货增速 is not None and 营收增速 is not None
            and 存货增速 > 0 and (存货增速 - 营收增速) > _存货超营收增速_GAP):
        hit_压货 = True
        val_压货.update({"存货增速": 存货增速, "营收增速": 营收增速,
                        "存货超营收pct": round(存货增速 - 营收增速, 4)})
    if hit_压货:
        add("经销商压货", "中", val_压货)

    # ③ 毛利率下滑/品牌溢价流失 —— 中
    # 说明:食饮本应高毛利;单期毛利率低于阈值作代理(提价乏力/促销加码/品牌溢价流失)。
    #      精确"毛利环比连续下滑"判据需多期序列(单期 derived 无历史,见假设)。
    毛利率 = derived.get("毛利率")
    if 毛利率 is not None and 毛利率 < _LO_毛利率:
        add("品牌溢价流失", "中", {"毛利率": round(毛利率, 4), "下限pct": _LO_毛利率,
                              "NOTE": "食饮本应高毛利,低于阈值提示提价乏力/促销加码"})

    # ④ 现金流质量背离(消费股应现金充沛)—— 高
    # 判据:归母为正而 CFO 为负,或 CFO/归母 过低。消费股先款后货本应现金充沛,背离=利润质量强红旗。
    归母 = 利润表.get("归母净利润")
    CFO = 现金流量表.get("经营活动现金流量净额")
    现金含量 = derived.get("现金含量_CFO比净利")
    if isinstance(归母, (int, float)) and 归母 > 0:
        if isinstance(CFO, (int, float)) and CFO < 0:
            add("现金流质量背离", "高",
                {"归母净利润": 归母, "经营活动现金流量净额": CFO,
                 "NOTE": "消费股本应现金充沛,归母正而 CFO 负=强背离"})
        elif 现金含量 is not None and 现金含量 < _LO_现金含量:
            add("现金含量偏低", "中",
                {"现金含量_CFO比净利": round(现金含量, 4), "下限": _LO_现金含量,
                 "NOTE": "消费股本应现金充沛,现金含量偏低=利润质量存疑"})

    return flags
