# ── 专属红旗阈值(工程占位,待标定)────────────────────────────
_GM_DROP_PCT = -5.0    # 毛利率同比降幅达此(百分点)→ 煤价下行(周期见顶后利润快速回落)


def _num(rec, *path):
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """煤炭专属红旗。仅 命中=True 者并入;缺值不命中不抛异常。阈值工程占位待标定。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code, sev, val):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # 1) 煤价下行(毛利率大降):毛利率同比降幅达阈,周期见顶利润快速回落。
    gm = derived.get("毛利率同比升")
    if gm is not None and gm <= _GM_DROP_PCT:
        emit("煤价下行", "中", {"毛利率同比升pct": round(gm, 4), "阈值pct": _GM_DROP_PCT,
                            "NOTE": "毛利率同比大幅回落,煤价周期见顶信号"})

    # 2) 经营现金流恶化:账面盈利却经营现金净流出(景气期本应现金充沛,失血=异常)。
    归母净利 = _num(structured, "利润表", "归母净利润")
    CFO = _num(structured, "现金流量表", "经营活动现金流量净额")
    if 归母净利 is not None and 归母净利 > 0 and CFO is not None and CFO < 0:
        emit("经营现金流恶化", "中", {"归母净利润": 归母净利, "经营活动现金流量净额": CFO,
                              "NOTE": "煤炭景气期本应现金充沛,盈利却现金净流出属异常"})

    return out
