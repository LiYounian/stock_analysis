# ── 专属红旗阈值(工程占位,待标定)────────────────────────────
_GM_DROP_PCT = -4.0     # 毛利率同比降幅达此(百分点)→ 油价下行/炼化价差收窄
_INV_GAP_PCT = 30.0     # 存货增速−营收增速 超此(pct)且毛利率走弱 → 高价库存跌价风险


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """石油石化专属红旗。仅 命中=True 者并入;缺值不命中不抛异常。阈值工程占位待标定。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code, sev, val):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    gm = derived.get("毛利率同比升")

    # 1) 炼化价差收窄(毛利率走弱):毛利率同比降幅达阈,油价下行/价差压缩。
    if gm is not None and gm <= _GM_DROP_PCT:
        emit("炼化价差收窄", "中", {"毛利率同比升pct": round(gm, 4), "阈值pct": _GM_DROP_PCT})

    # 2) 存货跌价风险:存货增速远超营收增速且毛利率同步走弱(高价原油/成品油库存,油价急跌时减值)。
    inv, rev = derived.get("存货增速"), derived.get("营收增速")
    if (inv is not None and rev is not None and gm is not None
            and inv > 0 and (inv - rev) > _INV_GAP_PCT and gm < 0):
        emit("存货跌价风险", "中", {"存货增速": inv, "营收增速": rev,
                              "差值pct": round(inv - rev, 4), "毛利率同比升pct": round(gm, 4),
                              "NOTE": "高价库存叠加毛利走弱,油价急跌时存货跌价损失风险"})

    return out
