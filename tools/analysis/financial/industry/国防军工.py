# 本行业不适用/会误杀的通用红旗:
#   现金含量不足 —— 军方回款账期长导致 CFO 常年弱于账面利润是**行业特性**,通用版会系统性误杀,SKIP;
#                改用更严的专属"经营现金流恶化"(归母为正而 CFO 为负)。
# 应收激增/高负债:保留通用判定(应收激增对军工仍是真实坏账信号,只是叠加专属口径互补)。
SKIP_FLAGS = ["现金含量不足"]


# ── 专属红旗阈值(工程占位,待标定)──────────────────────────────────────
_LO_合同负债环比 = -10.0       # 合同负债(预收)环比 低于此 pct → 在手订单能见度下滑
_HI_应收超营收增速_GAP = 20.0  # 应收增速 领先 营收增速 超此 pct → 回款恶化(账期进一步拉长/坏账)
_HI_存货超营收增速_GAP = 25.0  # 存货增速 领先 营收增速 超此 pct → 在产/发出商品积压(交付/确认放缓)
_LO_研发费用率_pct = 3.0       # 研发费用率 低于此 → 研发投入不足(军工技术壁垒隐忧)
_LO_毛利率 = 10.0             # 毛利率 低于此 → 定价机制变化/降价压力


def _ratio(a, b):
    """a/b;a、b 任一 None 或 |b|≈0 → None。"""
    if a is None or b is None or abs(b) < 1e-9:
        return None
    return a / b


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """国防军工专属红旗。返回 [{code,命中,严重度,值}, ...](调用方仅并入 命中=True 的)。
    单期、纯函数,一切缺值→不命中,不抛异常。阈值为工程占位,**待标定**。"""
    derived = derived or {}
    利润表 = (structured or {}).get("利润表", {}) if isinstance(structured, dict) else {}
    现金流量表 = (structured or {}).get("现金流量表", {}) if isinstance(structured, dict) else {}

    flags: list[dict] = []

    def add(code, sev, val):
        flags.append({"code": code, "命中": True, "严重度": sev, "值": val})

    营收增速 = derived.get("营收增速")
    归母 = 利润表.get("归母净利润")

    # ① 订单能见度下滑(合同负债/预收环比走弱)—— 中
    # 判据:合同负债环比 显著为负 → 在手订单(预收款)减少,未来营收保障走弱。这是军工最前瞻的预警。
    合同负债环比 = derived.get("合同负债环比")
    if 合同负债环比 is not None and 合同负债环比 < _LO_合同负债环比:
        add("订单能见度下滑", "中",
            {"合同负债环比%": round(合同负债环比, 4), "下限%": _LO_合同负债环比,
             "NOTE": "预收/合同负债环比走弱,在手订单转弱"})

    # ② 应收回款恶化(应收增速跑赢营收)—— 中
    # 判据:应收增速 领先 营收增速 超阈值。军方账期本长,应收再显著跑赢营收=回款进一步恶化/坏账风险。
    应收增速 = derived.get("应收增速")
    if (应收增速 is not None and 营收增速 is not None
            and 应收增速 > 0 and (应收增速 - 营收增速) > _HI_应收超营收增速_GAP):
        add("应收回款恶化", "中",
            {"应收增速": 应收增速, "营收增速": 营收增速, "差值pct": round(应收增速 - 营收增速, 4),
             "NOTE": "军方账期长,应收增速显著超营收=回款恶化/坏账"})

    # ③ 存货积压(在产/发出商品,交付确认放缓)—— 中
    # 判据:存货增速 领先 营收增速 超阈值,且存货在增。军品在产周期长,存货远超营收=交付/收入确认放缓。
    存货增速 = derived.get("存货增速")
    if (存货增速 is not None and 营收增速 is not None
            and 存货增速 > 0 and (存货增速 - 营收增速) > _HI_存货超营收增速_GAP):
        add("存货积压", "中",
            {"存货增速": 存货增速, "营收增速": 营收增速, "差值pct": round(存货增速 - 营收增速, 4),
             "NOTE": "在产品/发出商品积压,交付或收入确认放缓"})

    # ④ 研发投入不足(技术壁垒隐忧)—— 低
    # 判据:研发费用率 低于阈值。军工靠技术壁垒,研发偏低=竞争力隐忧(与多数行业"研发高=烧钱"相反)。
    研发费用率 = derived.get("研发费用率")
    if 研发费用率 is not None and 0 <= 研发费用率 < _LO_研发费用率_pct:
        add("研发投入不足", "低",
            {"研发费用率%": round(研发费用率, 4), "下限%": _LO_研发费用率_pct,
             "NOTE": "军工靠技术壁垒,研发偏低=竞争力隐忧"})

    # ⑤ 毛利率骤降(定价机制变化/降价压力)—— 中
    # 说明:单期毛利率低于阈值作代理;环比骤降需多期序列(单期 derived 无历史,见假设)。
    毛利率 = derived.get("毛利率")
    if 毛利率 is not None and 毛利率 < _LO_毛利率:
        add("毛利率承压", "中", {"毛利率": round(毛利率, 4), "下限pct": _LO_毛利率,
                            "NOTE": "定价机制变化/降价压力"})

    # ⑥ 经营现金流恶化(归母为正而 CFO 为负)—— 中
    # 判据:替代被 SKIP 的通用"现金含量不足",更严:仅当账面盈利(归母>0)却 CFO 为负才发声,避免误杀。
    CFO = 现金流量表.get("经营活动现金流量净额")
    if (isinstance(归母, (int, float)) and 归母 > 0
            and isinstance(CFO, (int, float)) and CFO < 0):
        add("经营现金流恶化", "中", {"归母净利润": 归母, "经营活动现金流量净额": CFO,
                              "NOTE": "账面盈利却经营现金净流出,回款质量存疑"})

    return flags
