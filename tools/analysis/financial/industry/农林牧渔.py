# ── 专属红旗阈值(工程占位,待标定)────────────────────────────
_INV_GAP_PCT = 30.0     # 存货增速−营收增速 超此(pct)且存货增长→ 生物资产(存栏)累积/跌价减值风险
_AR_GAP_PCT = 20.0      # (备用)应收增速−营收增速


def _num(rec, *path):
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """农林牧渔专属红旗。仅 命中=True 者并入;缺值不命中不抛异常。阈值工程占位待标定。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code, sev, val):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # 1) 生物资产堆积(存货激增于营收):存栏累积或跌价减值风险(区别于旺季正常备栏,叠加增速差阈值)。
    inv, rev = derived.get("存货增速"), derived.get("营收增速")
    if inv is not None and rev is not None and inv > 0 and (inv - rev) > _INV_GAP_PCT:
        emit("生物资产堆积", "中", {"存货增速": inv, "营收增速": rev,
                              "差值pct": round(inv - rev, 4), "阈值pct": _INV_GAP_PCT,
                              "NOTE": "生物资产(存栏)增速远超营收=累库/存栏积压,叠加价格下行有跌价减值风险"})

    # 2) 下行周期现金失血:账面亏损(归母<0)且经营现金流为负 → 猪周期底部资金链风险。
    归母净利 = _num(structured, "利润表", "归母净利润")
    CFO = _num(structured, "现金流量表", "经营活动现金流量净额")
    if 归母净利 is not None and 归母净利 < 0 and CFO is not None and CFO < 0:
        emit("周期现金失血", "高", {"归母净利润": 归母净利, "经营活动现金流量净额": CFO,
                              "NOTE": "亏损叠加经营现金净流出,周期底部资金链承压"})

    return out
