# ── 专属红旗阈值(工程占位,待标定)────────────────────────────
_CONTRACT_DROP_PCT = -10.0   # 合同负债(预收)环比 低于此(pct)→ 预订/预售景气转弱,需求转冷前瞻


def _num(rec, *path):
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """社会服务专属红旗。仅 命中=True 者并入;缺值不命中不抛异常。阈值工程占位待标定。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code, sev, val):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # 1) 预订景气转弱:合同负债(预收/会员卡)环比走弱 → 未来客流/入住/预订下滑前瞻。
    c = derived.get("合同负债环比")
    if c is not None and c <= _CONTRACT_DROP_PCT:
        emit("预订景气转弱", "中", {"合同负债环比pct": round(c, 4), "阈值pct": _CONTRACT_DROP_PCT,
                              "NOTE": "预收/合同负债环比走弱,需求转冷前瞻"})

    # 2) 经营现金流恶化:账面盈利却经营现金净流出(服务业本应现金好,失血=异常)。
    归母净利 = _num(structured, "利润表", "归母净利润")
    CFO = _num(structured, "现金流量表", "经营活动现金流量净额")
    if 归母净利 is not None and 归母净利 > 0 and CFO is not None and CFO < 0:
        emit("经营现金流恶化", "中", {"归母净利润": 归母净利, "经营活动现金流量净额": CFO,
                              "NOTE": "服务业本应预收沉淀现金,盈利却现金净流出属异常"})

    return out
