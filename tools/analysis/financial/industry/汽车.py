"""汽车(整车)财报专家(P0 数值层)。⚠️ 非投资建议;阈值为工程占位待标定。

行业画像:重资产制造 + 规模效应,单车利润薄如刀片,"销量 × 单车利润"定生死。
财报口径要点:
  - 毛利率天然偏低且分化(燃油约 10%~18%,新能源自主更薄),看**趋势**比看绝对值更重要;
    价格战下毛利率承压,通用 0→50 的毛利率区间会让整车长期低分失真,故**下调质量区间**。
  - 政府补助/非经常损益占比高 → **扣非净利才是真经营**,质量维度以扣非占归母提权。
  - 对上下游双向占款(经销商压货、供应商账期),CFO 常好于账面利润,故现金含量上限拉高;
    但"利润为正而 CFO 为负"是压货/占款反噬的强信号,单列专属红旗。
  - 重资产高杠杆属常态 → **不 skip 高负债**,改由 dimension_specs 放宽资产负债率区间承接。

阈值/区间/权重均为工程占位,注释注明"待标定"。纯函数、无状态、缺值→不命中/None,不抛异常。
"""
from __future__ import annotations

KEY = "汽车"  # 申万一级规范名(必须正好这个字符串,否则路由不到)
NOTE = ("整车重资产薄毛利:以**扣非净利**看真经营(补助/非经常损益占比高),毛利率看趋势而非绝对值;"
        "CFO 常好于利润(占款),但利润正而 CFO 负=压货反噬;高负债属常态(区间已放宽)。")


def dimension_specs() -> dict:
    """覆写五维子指标区间(格式同 scoring.dimension_specs):{维度: [(显示名, derived键, 0分端, 100分端)]}。
    反向指标 0分端 > 100分端。区间为工程占位,**待策略提供者标定**。"""
    return {
        # 成长:整车成长温和;扣非增速弱化补助水分
        "成长": [("营收增速%", "营收增速", -15, 40),
               ("扣非净利增速%", "扣非净利增速", -20, 50)],
        # 质量(最重):毛利率区间大幅下调(薄毛利);扣非占归母识别补助依赖;现金含量上限拉高(占款)
        "质量": [("毛利率%", "毛利率", 5, 25),
               ("扣非占归母", "扣非占归母", 0.6, 1.0),
               ("现金含量 CFO/归母", "现金含量_CFO比净利", 0, 1.5)],
        # 健康:重资产容忍度高于轻资产,资产负债率区间放宽(承接不 skip 的高负债)
        "健康": [("资产负债率%(反向)", "资产负债率", 80, 45),
               ("短债覆盖", "短债覆盖", 0, 1.5)],
        # 运营:整车经销商现款/短账期、成车周转快,周转天数区间收紧
        "运营": [("应收周转天数(反向)", "应收周转天数", 90, 20),
               ("存货周转天数(反向)", "存货周转天数", 120, 40)],
        "回报": [("ROE%", "ROE", 0, 15)],
    }


def weights() -> dict | None:
    """覆写五维权重。质量最重(扣非质量+毛利决定整车是否真赚钱)。权重为工程占位,待标定。"""
    return {"成长": 0.15, "质量": 0.30, "健康": 0.15, "运营": 0.20, "回报": 0.20}


# 通用红旗中不适用/被专属版本取代的:
#   增收不增利 —— 通用版基于"归母"(易被补助/非经常损益扰动),整车改用**扣非**口径的
#   价格战版(以价换量)更贴切,故跳过通用版避免口径重复/双计。
# 高负债:重资产高杠杆属常态,**不 skip**,由 dimension_specs 放宽资产负债率区间处理。
SKIP_FLAGS = ["增收不增利"]


def _num(rec: dict | None, *path: str):
    """安全取嵌套数值科目;任一层缺/非数 → None(不抛)。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """整车专属红旗。返回 [{code,命中,严重度,值}, ...](调用方仅并入 命中=True 的)。
    一切缺值 → 不命中,不抛异常。阈值为工程占位,**待标定**。"""
    derived = derived or {}
    利润表 = (structured or {}).get("利润表", {}) if isinstance(structured, dict) else {}
    现金流量表 = (structured or {}).get("现金流量表", {}) if isinstance(structured, dict) else {}
    资产负债表 = (structured or {}).get("资产负债表", {}) if isinstance(structured, dict) else {}

    flags: list[dict] = []

    def add(code, hit, sev, val):
        flags.append({"code": code, "命中": bool(hit), "严重度": sev, "值": val})

    # ① 增收不增利(价格战/以价换量)—— 高
    # 判据:营收增速 >0 且 扣非净利增速 落后营收增速 20pct 以上(即便扣非仍正,增速掉队=薄利换量)。
    # 阈值 20pct 为工程占位,待标定。
    营收增速 = derived.get("营收增速")
    扣非增速 = derived.get("扣非净利增速")
    _GAP_价格战 = 20.0  # 待标定
    if 营收增速 is not None and 扣非增速 is not None and 营收增速 > 0 and (营收增速 - 扣非增速) > _GAP_价格战:
        add("增收不增利_价格战", True, "高",
            {"营收增速": 营收增速, "扣非净利增速": 扣非增速, "差值pct": round(营收增速 - 扣非增速, 4)})

    # ② 靠补助/非经常损益撑利润 —— 高
    # 判据:扣非占归母 < 0.6,或(归母为正而扣非为负)。扣非-归母之差即"非经常损益整体规模"的近似。
    # 阈值 0.6 为工程占位,待标定。
    扣非占归母 = derived.get("扣非占归母")
    归母 = 利润表.get("归母净利润")
    扣非 = 利润表.get("扣非归母净利润")
    _LO_扣非占比 = 0.6  # 待标定
    hit_补助 = False
    val_补助: dict = {}
    if 扣非占归母 is not None and 扣非占归母 < _LO_扣非占比:
        hit_补助 = True
        val_补助 = {"扣非占归母": round(扣非占归母, 4), "下限": _LO_扣非占比}
    elif isinstance(归母, (int, float)) and isinstance(扣非, (int, float)) and 归母 > 0 > 扣非:
        hit_补助 = True
        val_补助 = {"归母净利润": 归母, "扣非归母净利润": 扣非, "说明": "归母正而扣非负"}
    if hit_补助:
        add("靠补助撑利润", True, "高", val_补助)

    # ③ 毛利率承压(价格战/规模不足)—— 中
    # 说明:方案理想判据为"毛利率环比连续 2 季下滑且累计 >3pct",但单期 derived 无历史环比序列,
    #      此处以**单期毛利率低于阈值**作代理(趋势判据需多期,见方案 §③-3 / 实现状态假设)。
    # 阈值 8% 为工程占位,待标定。
    毛利率 = derived.get("毛利率")
    _LO_毛利率 = 8.0  # 待标定
    if 毛利率 is not None and 毛利率 < _LO_毛利率:
        add("毛利率承压", True, "中", {"毛利率": round(毛利率, 4), "下限pct": _LO_毛利率})

    # ④ 经营现金流恶化(压货/占款反噬)—— 中
    # 判据:归母净利为正而经营活动现金流量净额为负(账面赚钱但没收到现金)。
    CFO = 现金流量表.get("经营活动现金流量净额")
    if isinstance(归母, (int, float)) and isinstance(CFO, (int, float)) and 归母 > 0 > CFO:
        add("经营现金流恶化", True, "中", {"归母净利润": 归母, "经营活动现金流量净额": CFO})

    # ⑤ 研发资本化激进(利润质量)—— 中
    # 说明:真源"资本化研发/总研发"需正文附注,表内无直接拆分;此处以
    #      开发支出(资本化研发存量)/ 研发费用(当期费用化) 作**粗代理**,比值偏高提示资本化倾向重。
    # 阈值 1.0 为工程占位,待标定;仅作发声用,精确资本化率需正文核。
    开发支出 = 资产负债表.get("开发支出")
    研发费用 = 利润表.get("研发费用")
    _HI_资本化 = 1.0  # 待标定
    if (isinstance(开发支出, (int, float)) and isinstance(研发费用, (int, float))
            and 研发费用 > 0 and 开发支出 / 研发费用 > _HI_资本化):
        add("研发资本化激进", True, "中",
            {"开发支出": 开发支出, "研发费用": 研发费用, "开发支出比研发费用": round(开发支出 / 研发费用, 4)})

    return flags
