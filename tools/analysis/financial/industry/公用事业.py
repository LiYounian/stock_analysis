# ── 专属红旗阈值(工程占位,待标定)────────────────────────────
_AR_GAP_PCT = 20.0     # 应收增速−营收增速 超此(pct)→ 电费/气费回收恶化(应收膨胀)
_GM_DROP_PCT = -3.0    # 毛利率同比降幅达此(百分点)→ 燃料成本(煤价)挤压毛利


def _num(rec, *path):
    """安全取嵌套数值科目;任一层缺/非数 → None。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """公用事业专属红旗。返回 [{code,命中,严重度,值}, ...](仅 命中=True 者并入)。
    单期、纯函数,一切缺值→不命中,不抛异常。阈值工程占位待标定。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code, sev, val):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # 1) 应收膨胀(电费/气费回收恶化):应收增速显著超营收增速。
    _ar = derived.get("应收营收增速差")
    if _ar is None:
        a, r = derived.get("应收增速"), derived.get("营收增速")
        _ar = (a - r) if (a is not None and r is not None) else None
    if _ar is not None and _ar > _AR_GAP_PCT:
        emit("应收膨胀", "中", {"应收营收增速差pct": round(_ar, 4), "阈值pct": _AR_GAP_PCT,
                            "NOTE": "电费/气费回收恶化,应收随管制营收异常膨胀"})

    # 2) 燃料成本挤压毛利:毛利率同比降幅达阈(煤价/气价上行,火电/燃气承压)。
    gm = derived.get("毛利率同比升")
    if gm is not None and gm <= _GM_DROP_PCT:
        emit("燃料成本挤压毛利", "中", {"毛利率同比升pct": round(gm, 4), "阈值pct": _GM_DROP_PCT})

    return out
