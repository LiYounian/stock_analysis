# ── 专属红旗阈值(工程占位,待标定)────────────────────────────
_INV_GAP_PCT = 20.0     # 存货增速−营收增速 超此(pct)且存货增长→ 滞销累库(过季/尾货)
_AR_GAP_PCT = 20.0      # 应收增速−营收增速 超此(pct)→ 应收异常膨胀(零售本应现结/低应收)


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """商贸零售专属红旗。仅 命中=True 者并入;缺值不命中不抛异常。阈值工程占位待标定。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code, sev, val):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # 1) 存货滞销累库:存货增速显著超营收增速(零售存货积压=过季/尾货,去化差)。
    inv, rev = derived.get("存货增速"), derived.get("营收增速")
    if inv is not None and rev is not None and inv > 0 and (inv - rev) > _INV_GAP_PCT:
        emit("存货滞销累库", "中", {"存货增速": inv, "营收增速": rev,
                              "差值pct": round(inv - rev, 4), "阈值pct": _INV_GAP_PCT})

    # 2) 应收异常膨胀:零售本应现结、应收占比低,应收增速远超营收=赊销冲收入或坏账风险。
    _ar = derived.get("应收营收增速差")
    if _ar is None:
        a, r = derived.get("应收增速"), derived.get("营收增速")
        _ar = (a - r) if (a is not None and r is not None) else None
    if _ar is not None and _ar > _AR_GAP_PCT:
        emit("应收异常膨胀", "中", {"应收营收增速差pct": round(_ar, 4), "阈值pct": _AR_GAP_PCT})

    return out
