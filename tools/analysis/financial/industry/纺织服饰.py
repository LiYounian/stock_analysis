# ── 专属红旗阈值(工程占位,待标定)────────────────────────────
_INV_GAP_PCT = 20.0     # 存货增速−营收增速 超此(pct)且存货增长→ 过季/尾货积压(跌价减值风险)
_AR_GAP_PCT = 20.0      # 应收增速−营收增速 超此(pct)→ 渠道压货/加盟商回款恶化


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """纺织服饰专属红旗。仅 命中=True 者并入;缺值不命中不抛异常。阈值工程占位待标定。"""
    derived = derived or {}
    out: list[dict] = []

    def emit(code, sev, val):
        out.append({"code": code, "命中": True, "严重度": sev, "值": val})

    rev = derived.get("营收增速")

    # 1) 存货积压(过季/尾货贬值):存货增速显著超营收增速,服装库存跌价减值+现金占用。
    inv = derived.get("存货增速")
    if inv is not None and rev is not None and inv > 0 and (inv - rev) > _INV_GAP_PCT:
        emit("存货积压", "中", {"存货增速": inv, "营收增速": rev,
                            "差值pct": round(inv - rev, 4), "阈值pct": _INV_GAP_PCT,
                            "NOTE": "服装过季/尾货贬值快,存货增速远超营收=积压+跌价减值风险"})

    # 2) 应收膨胀(渠道压货/加盟商回款恶化):应收增速远超营收增速。
    _ar = derived.get("应收营收增速差")
    if _ar is None:
        a = derived.get("应收增速")
        _ar = (a - rev) if (a is not None and rev is not None) else None
    if _ar is not None and _ar > _AR_GAP_PCT:
        emit("应收膨胀", "中", {"应收营收增速差pct": round(_ar, 4), "阈值pct": _AR_GAP_PCT})

    return out
