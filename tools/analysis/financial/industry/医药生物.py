"""医药生物(申万一级,含化药/生物药/中药/医疗器械/医疗服务)财报专家(P0 数值层)。
⚠️ 非投资建议;阈值/区间/权重均为工程占位,待策略提供者标定。

行业画像:高毛利、强研发、强监管,**创新药(看研发/现金流/管线)与仿制药·中药(看毛利/周转)两套逻辑**。
  - 研发投入大且允许资本化:开发支出(资本化研发存量)/研发费用(费用化)偏高 → **过度资本化 = 把本该费用化
    的研发挂在资产上、虚增当期利润**,是本行业头号利润质量红旗(创新药药企尤甚)。
  - 集采(带量采购)降价冲击:中标即以价换量,毛利率**骤降**;仿制药/中药毛利被系统性压缩,单期低毛利 +
    营收失速是集采出清的数值特征(单期无历史环比,以低毛利 + 营收增速塌陷作代理,精确判需多期)。
  - 应收账款风险(商业贿赂/带金销售):医药销售费用高、渠道回款链条长,应收/营收偏高或应收增速远超营收增速
    提示回款质量差 / 带金销售依赖,是合规暴雷的粗代理(真实销售费用结构待正文补采)。
  - 存货药品效期减值:药品有效期短,存货积压(存货增速远超营收、周转天数拉长)→ 效期临近跌价减值风险。
  - 商誉并购减值暴雷:医药并购频繁、商誉高企,业绩承诺到期后减值暴雷高发 → 本行业**上调为高严重度**,
    故 SKIP 通用「商誉高企」(中性口径),改用专属高严重度「商誉减值暴雷风险」。
  - 管线依赖单品:单一大品种贡献主要收入,专利悬崖/竞品放量即断崖;属正文附注(产品收入拆分),表内无直接
    科目,**不硬判**(缺数据不误杀),NOTE 标注待补采。
  - 高负债非本行业常态(药企多轻资产高毛利、现金较厚),故**不 skip 高负债**,交通用区间承接。

阈值/区间/权重均为工程占位,注释注明"待标定"。纯函数、无状态、缺值→不命中/None,不抛异常。
"""
