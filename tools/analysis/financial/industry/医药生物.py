# 本行业处理的通用红旗:
#   商誉高企 —— 医药并购频繁、业绩承诺到期减值暴雷高发,通用中性口径**低估严重度**,SKIP 后改用专属
#   高严重度「商誉减值暴雷风险」,避免同一信号双计且更贴行业风险。
# 高负债:药企多轻资产高毛利、现金较厚,高负债非常态,**不 skip**,交通用区间承接。
SKIP_FLAGS = ["商誉高企"]


def _ratio(a, b):
    """a/b;a、b 任一 None 或 |b|≈0 → None。"""
    if a is None or b is None or abs(b) < 1e-9:
        return None
    return a / b


# ── 专属红旗阈值(工程占位,待标定)──────────────────────────────────────
_HI_研发资本化比 = 1.0        # 开发支出 / 研发费用 高于此 → 过度资本化(虚增利润)
_LO_毛利率_集采 = 30.0        # 毛利率 低于此 → 集采/价格战压缩(医药本应高毛利)
_集采营收失速_上限 = -10.0    # 营收增速 低于此(负增)配合低毛利 → 集采出清代理
_HI_应收占营收 = 0.5         # 应收账款 / 营收 高于此 → 回款质量差/带金销售(粗代理)
_应收超营收增速_GAP = 20.0    # 应收增速 领先 营收增速 超此 pct → 应收激增(带金销售/回款恶化)
_存货超营收增速_GAP = 20.0    # 存货增速 领先 营收增速 超此 pct → 药品积压(效期减值风险)
_HI_商誉占净资产 = 0.30       # 商誉 / 归母净资产 高于此 → 并购减值暴雷风险(专属高严重度)
_LO_现金含量 = 0.3           # CFO/归母 低于此(且归母为正)→ 账面利润远超经营现金流


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """医药生物专属红旗。返回 [{code,命中,严重度,值}, ...](调用方仅并入 命中=True 的)。
    单期、纯函数,一切缺值→不命中,不抛异常。阈值为工程占位,**待标定**。"""
    derived = derived or {}
    利润表 = (structured or {}).get("利润表", {}) if isinstance(structured, dict) else {}
    资产负债表 = (structured or {}).get("资产负债表", {}) if isinstance(structured, dict) else {}
    现金流量表 = (structured or {}).get("现金流量表", {}) if isinstance(structured, dict) else {}

    flags: list[dict] = []

    def add(code, sev, val):
        flags.append({"code": code, "命中": True, "严重度": sev, "值": val})

    # ① 研发过度资本化(虚增利润)—— 高【本行业头号利润质量红旗】
    # 说明:真源"资本化研发/总研发"需正文附注,表内以 开发支出(资本化存量)/研发费用(当期费用化) 作**粗代理**,
    #      比值偏高提示把本应费用化的研发挂在资产上、虚增当期利润。阈值 1.0 为工程占位,待标定。
    开发支出 = 资产负债表.get("开发支出")
    研发费用 = 利润表.get("研发费用")
    if (isinstance(开发支出, (int, float)) and isinstance(研发费用, (int, float))
            and 研发费用 > 0 and 开发支出 / 研发费用 > _HI_研发资本化比):
        add("研发过度资本化", "高",
            {"开发支出": 开发支出, "研发费用": 研发费用,
             "开发支出比研发费用": round(开发支出 / 研发费用, 4),
             "NOTE": "资本化研发/总研发的粗代理,过度资本化=虚增利润,精确资本化率待正文核"})

    # ② 集采降价冲击(毛利骤降)—— 高
    # 说明:集采中标以价换量,毛利率骤降;单期无历史环比,以 单期毛利率低于阈值(医药本应高毛利)
    #      作代理,叠加营收失速则更强。精确"毛利环比连续下滑"判据需多期序列(见假设)。
    毛利率 = derived.get("毛利率")
    营收增速 = derived.get("营收增速")
    if 毛利率 is not None and 毛利率 < _LO_毛利率_集采:
        val = {"毛利率": round(毛利率, 4), "下限pct": _LO_毛利率_集采,
               "NOTE": "医药本应高毛利,低于阈值提示集采/价格战压缩"}
        if 营收增速 is not None and 营收增速 < _集采营收失速_上限:
            val["营收增速"] = 营收增速
        add("集采降价冲击", "高", val)

    # ③ 应收账款风险(带金销售/回款质量)—— 中
    # 判据:应收账款/营收 偏高,或 应收增速 远超营收增速。医药销售链条长、销售费用高,回款质量差/带金销售的粗代理。
    应收 = (资产负债表.get("应收账款")
          or 资产负债表.get("应收票据及应收账款"))
    营收 = 利润表.get("营业总收入") or 利润表.get("营业收入")
    r_ar = _ratio(应收, 营收)
    应收增速 = derived.get("应收增速")
    hit_ar = False
    val_ar: dict = {"NOTE": "带金销售/回款质量的粗代理,真实销售费用结构待正文补采"}
    if r_ar is not None and r_ar > _HI_应收占营收:
        hit_ar = True
        val_ar.update({"应收账款": 应收, "营业收入": 营收, "应收占营收": round(r_ar, 4)})
    elif (应收增速 is not None and 营收增速 is not None
            and 应收增速 > 0 and (应收增速 - 营收增速) > _应收超营收增速_GAP):
        hit_ar = True
        val_ar.update({"应收增速": 应收增速, "营收增速": 营收增速,
                       "差值pct": round(应收增速 - 营收增速, 4)})
    if hit_ar:
        add("应收账款风险", "中", val_ar)

    # ④ 存货药品效期减值风险 —— 中
    # 判据:存货增速 领先 营收增速 超阈值且存货在增 → 药品积压,效期临近面临跌价减值。
    存货增速 = derived.get("存货增速")
    if (存货增速 is not None and 营收增速 is not None
            and 存货增速 > 0 and (存货增速 - 营收增速) > _存货超营收增速_GAP):
        add("存货效期减值风险", "中",
            {"存货增速": 存货增速, "营收增速": 营收增速, "差值pct": round(存货增速 - 营收增速, 4),
             "NOTE": "药品效期短,积压面临跌价减值"})

    # ⑤ 商誉减值暴雷风险 —— 高(替代通用中性口径「商誉高企」,已 SKIP)
    # 判据:商誉/归母净资产 偏高。医药并购频繁、业绩承诺到期减值暴雷高发,故上调为高严重度。
    商誉 = 资产负债表.get("商誉")
    归母净资产 = 资产负债表.get("归母股东权益") or 资产负债表.get("股东权益合计")
    r_gw = _ratio(商誉, 归母净资产)
    if r_gw is not None and r_gw > _HI_商誉占净资产:
        add("商誉减值暴雷风险", "高",
            {"商誉": 商誉, "归母净资产": 归母净资产, "商誉占净资产": round(r_gw, 4),
             "NOTE": "医药并购频繁,业绩承诺到期减值暴雷高发"})

    # ⑥ 经营现金流质量差 —— 中
    # 判据:归母为正而 CFO 为负,或 CFO/归母 过低。消费/医药本应现金较好,持续背离=利润质量存疑。
    归母 = 利润表.get("归母净利润")
    CFO = 现金流量表.get("经营活动现金流量净额")
    现金含量 = derived.get("现金含量_CFO比净利")
    if isinstance(归母, (int, float)) and 归母 > 0:
        if isinstance(CFO, (int, float)) and CFO < 0:
            add("经营现金流恶化", "中", {"归母净利润": 归母, "经营活动现金流量净额": CFO})
        elif 现金含量 is not None and 现金含量 < _LO_现金含量:
            add("现金含量偏低", "中", {"现金含量_CFO比净利": round(现金含量, 4), "下限": _LO_现金含量,
                                 "NOTE": "账面利润远超经营现金流"})

    return flags
