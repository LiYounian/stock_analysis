"""交通运输(航运/油运)财报专家(P0 数值层)。⚠️ 非投资建议;阈值为工程占位待标定。

行业画像:强周期 + 重资产 + 高经营杠杆。收入 = 运力 × 运价(TCE),成本大头是刚性折旧,
运价一涨增量几乎全落到利润(经营杠杆极高),一跌则固定成本吞噬利润甚至亏损。
故:
  - 弱化单季成长(周期波动极大),强化现金流与偿债安全边际;
  - 现金流通常好于利润(折旧非付现),现金含量应偏高;
  - 高杠杆是周期股命门,资产负债率提权重、放宽区间但不跳过;
  - 运价(BDTI/BCTI/TCE)在财报外,是真正先行指标,财务表只是结果 —— 展示层须提示。

契约见 docs/财报分析专家/模块开发规范.md §2;所有阈值/区间/权重均为工程占位,待策略提供者标定。
纯函数、无状态、无网络;一切取值/除法缺失 → 该项 None / 不命中,绝不抛异常。
"""
from __future__ import annotations

KEY = "交通运输"  # 申万一级规范名(注意非"交运"),否则 analyzer 路由不到
NOTE = ("航运=强周期重资产,盈利由运价(BDTI/BCTI/TCE,财报外)决定,单季暴涨暴跌属常态;"
        "评分弱化单季成长、强化现金流与偿债安全边际;单季分数仅供参考,须结合运价周期位置。")


# ———————————— 工程占位阈值(待策略提供者标定)————————————
_崩塌_归母同比_pct = -50.0      # 单季归母净利同比跌幅 ≤ 此值 → 视为运价暴跌致盈利崩塌
_崩塌_营收环比_pct = -25.0      # 单季营收环比跌幅 ≤ 此值(且毛利率低) → 盈利拐点向下
_崩塌_毛利率低_pct = 10.0       # 毛利率低于此值视为运价已回落到低景气
_双杀_资产负债率_pct = 65.0     # 资产负债率 > 此值 且盈利下行 → 戴维斯双杀
_有息负债占资产_pct = 30.0      # 有息负债/总资产 > 此值视为"有息负债高企"
_折旧占营收_上限 = 0.25         # (折旧+摊销)/营业总收入 > 此值视为重资产刚性成本过高


def _num(rec: dict | None, *path: str):
    """安全取嵌套数值科目;任一层缺失/非数 → None(对齐 flags._num)。"""
    cur = rec
    for k in path:
        if not isinstance(cur, dict):
            return None
        cur = cur.get(k)
    return cur if isinstance(cur, (int, float)) else None


def dimension_specs() -> dict:
    """覆写五维子指标区间(格式同 scoring.dimension_specs;反向指标 0分端>100分端)。

    相对通用的调整(见 方案 §④):
      成长:放宽双向(周期波动大)、加单季营收环比捕捉拐点;权重调低;
      质量:现金含量上移(折旧非付现,现金应强于利润);毛利率景气期可高;
      健康:资产负债率区间收紧+提权重(高杠杆是周期股命门);
      运营:仅留应收周转(航运应收账期短,无实物存货,存货周转不适用);
      回报:ROE 放宽下限(周期低谷可为负)。
    区间均为工程占位,待标定。
    """
    return {
        "成长": [("营收增速%", "营收增速", -30, 60),
               ("单季营收环比%", "单季营收环比", -30, 30)],
        "质量": [("毛利率%", "毛利率", 0, 40),
               ("现金含量 CFO/归母净利", "现金含量_CFO比净利", 0.5, 1.5)],
        "健康": [("资产负债率%(反向)", "资产负债率", 70, 35),
               ("短债覆盖", "短债覆盖", 0, 2)],
        "运营": [("应收周转天数(反向)", "应收周转天数", 90, 20)],
        "回报": [("ROE%", "ROE", -10, 25)],
    }


def weights() -> dict | None:
    """覆写五维权重:健康+回报+质量为主,成长对周期股意义弱(工程占位,待标定)。"""
    return {"成长": 0.10, "质量": 0.25, "健康": 0.30, "运营": 0.10, "回报": 0.25}


# 本行业不适用的通用红旗(§4 清单):
#   毛利率异常跳升 —— 周期股运价暴涨→毛利率骤升是常态,通用同比跳升会系统性误杀,以专属红旗替代;
#   短债覆盖不足   —— 重资产天然高有息负债,通用口径易误杀,改由专属"有息负债高企且短债覆盖不足"自算放宽。
SKIP_FLAGS = ["毛利率异常跳升", "短债覆盖不足"]


def extra_flags(derived: dict, structured: dict) -> list[dict]:
    """交运(航运)专属红旗。返回 [{code,命中,严重度,值}, ...];仅 命中=True 会被并入结果。

    全部用单期 derived 衍生 + structured 三大表 raw 自算(无未来函数、缺值→不命中、不抛)。
    """
    derived = derived or {}
    out: list[dict] = []

    营收增速 = derived.get("营收增速")
    归母增速 = derived.get("归母净利增速")     # 单季归母同比
    营收环比 = derived.get("单季营收环比")
    毛利率 = derived.get("毛利率")
    资产负债率 = derived.get("资产负债率")

    # 1) 运价下行致盈利崩塌(高):单季归母同比大幅转负,或营收环比骤降且毛利率已低。
    崩塌 = False
    依据: dict = {}
    if 归母增速 is not None and 归母增速 <= _崩塌_归母同比_pct:
        崩塌 = True
        依据["归母净利增速"] = round(归母增速, 4)
    if (营收环比 is not None and 营收环比 <= _崩塌_营收环比_pct
            and 毛利率 is not None and 毛利率 < _崩塌_毛利率低_pct):
        崩塌 = True
        依据["单季营收环比"] = round(营收环比, 4)
        依据["毛利率"] = round(毛利率, 4)
    if 崩塌:
        out.append({"code": "运价下行致盈利崩塌", "命中": True, "严重度": "高", "值": 依据})

    # 2) 高杠杆叠加运价下行(戴维斯双杀,高):高资产负债率 且 盈利/营收环比下行。
    盈利下行 = (归母增速 is not None and 归母增速 < 0) or (营收环比 is not None and 营收环比 < 0)
    if 资产负债率 is not None and 资产负债率 > _双杀_资产负债率_pct and 盈利下行:
        out.append({"code": "高杠杆叠加运价下行", "命中": True, "严重度": "高",
                    "值": {"资产负债率": round(资产负债率, 4),
                          "归母净利增速": (round(归母增速, 4) if 归母增速 is not None else None),
                          "单季营收环比": (round(营收环比, 4) if 营收环比 is not None else None)}})

    # 3) 有息负债高企且短债覆盖不足(中):货币资金 < 短期有息负债 且 有息负债占总资产偏高。
    货币资金 = _num(structured, "资产负债表", "货币资金")
    短借 = _num(structured, "资产负债表", "短期借款")
    一年内到期 = _num(structured, "资产负债表", "一年内到期非流动负债")
    长借 = _num(structured, "资产负债表", "长期借款")
    应付债券 = _num(structured, "资产负债表", "应付债券")
    资产总计 = _num(structured, "资产负债表", "资产总计")
    短期有息 = sum(x for x in (短借, 一年内到期) if x is not None) if (短借 is not None or 一年内到期 is not None) else None
    有息负债 = sum(x for x in (短借, 长借, 应付债券, 一年内到期) if x is not None) \
        if any(x is not None for x in (短借, 长借, 应付债券, 一年内到期)) else None
    if (货币资金 is not None and 短期有息 is not None and 短期有息 > 0 and 货币资金 < 短期有息
            and 有息负债 is not None and 资产总计 and (有息负债 / 资产总计 * 100) > _有息负债占资产_pct):
        out.append({"code": "有息负债高企且短债覆盖不足", "命中": True, "严重度": "中",
                    "值": {"货币资金": 货币资金, "短期有息负债": 短期有息, "有息负债": 有息负债,
                          "有息负债占总资产pct": round(有息负债 / 资产总计 * 100, 4)}})

    # 4) 经营现金流转负(高):折旧非付现,景气期 CFO 应远高于净利;转负=经营性失血。
    cfo = _num(structured, "现金流量表", "经营活动现金流量净额")
    if cfo is not None and cfo < 0:
        out.append({"code": "经营现金流转负", "命中": True, "严重度": "高", "值": {"经营活动现金流量净额": cfo}})

    # 5) 折旧占营收过高(中):重资产刚性成本,(折旧+摊销)/营业总收入 过高,常见于运价低迷营收萎缩。
    折旧 = _num(structured, "现金流量表", "固定资产折旧")
    摊销 = _num(structured, "现金流量表", "无形资产摊销")
    营业总收入 = _num(structured, "利润表", "营业总收入")
    折旧摊销 = sum(x for x in (折旧, 摊销) if x is not None) if (折旧 is not None or 摊销 is not None) else None
    if 折旧摊销 is not None and 营业总收入 and 营业总收入 > 0:
        比 = 折旧摊销 / 营业总收入
        if 比 > _折旧占营收_上限:
            out.append({"code": "折旧占营收过高", "命中": True, "严重度": "中",
                        "值": {"折旧摊销": 折旧摊销, "营业总收入": 营业总收入, "折旧占营收比": round(比, 4)}})

    return out
