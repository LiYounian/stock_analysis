_CSRC_PREFIX = re.compile(r"^([A-Z]\d{2})")


def to_sw(name: str) -> str | None:
    """任意行业名 → 申万一级名;无法对齐返回 None(交由上层弃权,不硬凑)。

    优先级:①已是申万一级 直接返回 → ②证监会前缀码 → ③别名精确 → ④别名/申万名 子串兜底。
    """
    if not name or not isinstance(name, str):
        return None
    s = name.strip()
    if not s:
        return None
    # ① 已是申万一级
    if s in SW_INDUSTRIES:
        return s
    # ② 证监会门类前缀码(A01/B06/C39…)
    m = _CSRC_PREFIX.match(s)
    if m:
        hit = CSRC_CODE_TO_SW.get(m.group(1))
        if hit:
            return hit
    low = s.lower()
    # ③ 别名精确(大小写不敏感)
    if low in ALIAS_TO_SW:
        return ALIAS_TO_SW[low]
    # ④ 子串兜底:输入包含某别名 / 某申万名(取最长匹配,避免"电子"误吞"电子元件"歧义时反而更准)
    cand: list[tuple[int, str]] = []
    for k, v in ALIAS_TO_SW.items():
        if k in low:
            cand.append((len(k), v))
    for sw in SW_INDUSTRIES:
        if sw in s:
            cand.append((len(sw), sw))
    if cand:
        cand.sort(reverse=True)                 # 最长匹配优先
        return cand[0][1]
    return None
